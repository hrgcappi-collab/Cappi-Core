#!/usr/bin/env python3
"""Проверка, что каждая кнопка бота действительно работает.

Запуск:  python3 selftest.py

Зачем именно так. Проверка импорта ничего не доказывает: файл может быть
валидным, а функции в нём — отсутствовать, и бот молча ответит «не понял»
на собственную кнопку. Так и случилось — одиннадцать пунктов меню были
мёртвыми, и выяснилось это от людей, а не из лога.

Поэтому здесь каждый экран вызывается по-настоящему, с живыми запросами
в Syrve, на сайт и в Glovo. Это медленно, около минуты, и это правильная
цена: быстрая проверка, которая ничего не ловит, хуже медленной.

Отправку в Telegram подменяем — сообщения никуда не уходят, но всё, что
экран делает до отправки, выполняется честно.
"""
import sys
import time

sys.path.insert(0, __import__("os").path.dirname(__file__) or ".")
import bot

ТЕСТОВЫЙ_ЧАТ = 0          # id не нужен: отправка подменена


def _необъявленные():
    """Ищем вызовы функций, которых в модуле нет.

    Появляется это при правках текстовой заменой: кусок кода попадает под
    замену вместе с соседями, и функция исчезает молча.
    """
    import ast
    дерево = ast.parse(open(bot.__file__).read())
    объявлены = {n.name for n in ast.walk(дерево)
                 if isinstance(n, ast.FunctionDef)}
    return sorted({n.func.id for n in ast.walk(дерево)
                   if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
                   and n.func.id.startswith("_")
                   and n.func.id not in объявлены})


# ---------------------------------------------------------------- проверки ТЗ
ПРЕДЕЛ_ЭКРАНА = 1400        # символов без разметки: влезает без долгой прокрутки
# Кнопки главного меню ведут в модуль и приносят его клавиатуру — это и
# есть следующий шаг, просто не кнопкой под текстом.
МОДУЛИ = {"💰 цены", "🛒 продажи", "📈 показатели", "🧑‍🍳 персонал",
          "🏭 производство", "🤖 джамшут", "🛠 админка"}
БЕЗ_ПЕРИОДА = МОДУЛИ | {   # экраны, которым период не нужен по смыслу
    "🚦 зоны сейчас", "🩺 здоровье", "🚚 в работе", "⏳ на проверке",
    "🔍 найти позицию", "📊 сайт и glovo", "🎯 план", "🛑 стоп-лист",
    "⭐ спецпредложение", "🏆 kpi кухни", "💵 процент кухни", "🕵️ тайный гость",
    "📅 выбрать день", "📅 смена за день", "🚧 закрыть зону", "✅ открыть зону",
    "🧮 себестоимость блюда", "📋 просчёт по составу", "➕ новое блюдо",
    "◀️ назад", "🔌 проверка связи", "⚙️ настройки", "🧭 состояние бота",
    "📜 журнал цен", "🗣 непонятые", "🔐 отказы", "🐞 сбои", "🔑 доступ",
    "👥 смена сегодня", "👥 смена вчера", "⏱ время работы",
}


def проверки_тз(собранное):
    """AC-06, AC-08, AC-10: длина callback_data, тупики, длина экрана."""
    import re as _re
    беды = []
    for кнопка, сообщения in собранное.items():
        for текст, кнопки in сообщения:
            for ряд in кнопки:
                for b in ряд:
                    д = len(str(b.get("callback_data", "")).encode())
                    if д > 64:
                        беды.append(f"AC-06 · {кнопка}: callback_data {д} байт — {b['callback_data'][:30]}")
            чистый = _re.sub(r"<[^>]+>", "", текст)
            if len(чистый) > ПРЕДЕЛ_ЭКРАНА:
                беды.append(f"AC-10 · {кнопка}: {len(чистый)} символов (предел {ПРЕДЕЛ_ЭКРАНА})")
        есть_кнопки = any(кнопки for _, кнопки in сообщения)
        if not есть_кнопки and кнопка not in БЕЗ_ПЕРИОДА:
            беды.append(f"AC-08 · {кнопка}: экран без следующего шага")
    return беды


def main():
    отправлено = []

    # Кнопки меню должны совпадать с обработчиками — это же бот проверяет
    # при старте, но здесь ошибка видна списком, а не отказом запуститься.
    bot._проверить_кнопки()

    # Функции, которые вызываются, но не объявлены. Ловится статически и
    # мгновенно — а иначе выясняется только когда до вызова дойдёт дело:
    # фоновый цикл падал в лог, и снаружи бот выглядел живым.
    пропало = _необъявленные()
    if пропало:
        print("❌ вызываются, но не объявлены: " + ", ".join(пропало))
        return 1

    # Telegram отводит на callback_data 64 байта. Превышение не ломает
    # кнопку по отдельности — оно роняет весь экран в «HTTP 400 Bad
    # Request», и по этому тексту причину не угадать.
    длинные = []
    исходный_say = bot.say
    собранное = {}
    текущая = {"кнопка": None}

    def перехват(chat, text, inline=None, keys=True):
        for ряд in (inline or []):
            for к in ряд:
                cd = к.get("callback_data", "")
                if len(cd.encode()) > 64:
                    длинные.append(cd)
        отправлено.append(text)
        собранное.setdefault(текущая["кнопка"], []).append((text, inline or []))

    bot.say = перехват

    ошибки, медленные = [], []
    for кнопка, экран in bot.BUTTONS.items():
        отправлено.clear()
        текущая["кнопка"] = кнопка
        t = time.time()
        беда = None
        try:
            экран(ТЕСТОВЫЙ_ЧАТ)
            if not отправлено:
                беда = "ничего не ответил"
        except Exception as e:
            беда = f"{type(e).__name__}: {e}"
        сколько = time.time() - t
        if беда:
            ошибки.append((кнопка, беда))
        if сколько > 5:
            медленные.append((кнопка, сколько))
        print(f"  {'❌' if беда else '✅'} {кнопка:<24} {сколько:>5.1f}с", flush=True)

    print(f"\nэкранов: {len(bot.BUTTONS)}")
    if медленные:
        print("дольше 5 секунд:")
        for к, с in sorted(медленные, key=lambda x: -x[1]):
            print(f"   {к:<24} {с:.1f}с")
    if длинные:
        print(f"\n❌ callback_data длиннее 64 байт: {len(длинные)}")
        for cd in длинные[:5]:
            print(f"   {len(cd.encode())} байт: {cd[:70]}")
        return 1
    if ошибки:
        print("\n❌ СЛОМАНЫ:")
        for к, e in ошибки:
            print(f"   {к:<24} {e[:100]}")
        return 1
    беды = проверки_тз(собранное)
    if беды:
        print(f"\n❌ нарушены требования ТЗ: {len(беды)}")
        for b in беды[:15]:
            print(f"   {b}")
        return 1
    print("\n✅ все экраны отвечают · требования ТЗ соблюдены")
    return 0


if __name__ == "__main__":
    sys.exit(main())


