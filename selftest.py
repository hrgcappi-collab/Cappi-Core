def проверки_кнопок():
    """Каждая кнопка экрана должна разбираться в on_button — и вовремя.

    13.09.2026 «📝 Дописать словами» отвечала «кнопка устарела» на нажатие
    секундной давности: её разбор стоял ниже проверки токена подтверждения,
    а токена у неё нет и не было. Человек нажал три раза и три раза получил
    отказ — на кнопку, которую бот сам только что показал.

    Проверяем статически, по исходнику: какие приставки бот раздаёт в
    `callback_data`, все ли они разбираются, и не оказалась ли какая-то за
    проверкой токена без права там быть.
    """
    import inspect
    src = inspect.getsource(bot)
    беды = []

    раздаёт = set(_re.findall(r'"callback_data":\s*f?"([a-zA-Zа-яА-Я]{2,3}):', src))
    раздаёт |= set(_re.findall(r'callback_data=f?"([a-zA-Zа-яА-Я]{2,3}):', src))
    тело = inspect.getsource(bot.on_button)
    разбирает = set(_re.findall(r'act\s*==\s*"([^"]+)"', тело))
    for группа in _re.findall(r'act\s+in\s+\(([^)]*)\)', тело):
        разбирает |= set(_re.findall(r'"([^"]+)"', группа))
    for пр in sorted(раздаёт - разбирает):
        беды.append(f"кнопка «{пр}:» раздаётся, но в on_button не разбирается")

    # Порядок: всё, что ниже проверки токена, обязано быть в ТОКЕННЫЕ.
    граница = тело.find("if act not in ТОКЕННЫЕ")
    # И приставка не должна разбираться дважды. «нб:» раздавали и
    # переключатель блока в настройках, и «создать карточку блюда»;
    # настройки стояли выше, токен блюда в их список не входил — и кнопка
    # молча открывала настройки. Ничего не падало, тесты были зелёные.
    if граница > 0:
        ранние = set(_re.findall(r'act\s*==\s*"([^"]+)"', тело[:граница]))
        for группа in _re.findall(r'act\s+in\s+\(([^)]*)\)', тело[:граница]):
            ранние |= set(_re.findall(r'"([^"]+)"', группа))
        for пр in sorted(ранние & bot.ТОКЕННЫЕ):
            беды.append(f"приставка «{пр}:» разбирается дважды — ранний разбор "
                        f"перехватит кнопку с токеном")
    if граница < 0:
        беды.append("в on_button нет защиты «act not in ТОКЕННЫЕ»")
    else:
        поздние = set(_re.findall(r'act\s*==\s*"([^"]+)"', тело[граница:]))
        for пр in sorted(поздние - bot.ТОКЕННЫЕ):
            беды.append(f"кнопка «{пр}:» разбирается после проверки токена — "
                        f"ответит «устарела»")
    return беды


def проверки_тз(собранное, ждут_ответа=()):
    """AC-06, AC-08, AC-10: длина callback_data, тупики, длина экрана."""
    беды = []
    for кнопка, сообщения in собранное.items():
        for текст, кнопки in сообщения:
            for ряд in кнопки:
                for b in ряд:
                    д = len(str(b.get("callback_data", "")).encode())
                    if д > 64:
                        беды.append(f"AC-06 · {кнопка}: callback_data {д} байт — {b['callback_data'][:30]}")
            чистый = _re.sub(r"<[^>]+>", "", текст)
            if len(чистый) > ПРЕДЕЛ_ЭКРАНА:
                беды.append(f"AC-10 · {кнопка}: {len(чистый)} символов (предел {ПРЕДЕЛ_ЭКРАНА})")
        # Экран, который ждёт ответа, — не тупик: следующий шаг у него
        # есть, просто не кнопкой, а вопросом («пришли артикул»).
        есть_кнопки = (any(кнопки for _, кнопки in сообщения)
                       or кнопка in ждут_ответа)
        if not есть_кнопки and кнопка not in БЕЗ_ПЕРИОДА:
            беды.append(f"AC-08 · {кнопка}: экран без следующего шага")
    return беды


def main():
    отправлено = []

    # Кнопки меню должны совпадать с обработчиками — это же бот проверяет
    # при старте, но здесь ошибка видна списком, а не отказом запуститься.
    bot._проверить_кнопки()

    # Функции, которые вызываются, но не объявлены. Ловится статически и
    # мгновенно — а иначе выясняется только когда до вызова дойдёт дело:
    # фоновый цикл падал в лог, и снаружи бот выглядел живым.
    пропало = _необъявленные()
    if пропало:
        print("❌ вызываются, но не объявлены: " + ", ".join(пропало))
        return 1

    кнопочные = проверки_кнопок()
    if кнопочные:
        print("❌ разбор кнопок:")
        for б in кнопочные:
            print(f"   {б}")
        return 1

    # Telegram отводит на callback_data 64 байта. Превышение не ломает
    # кнопку по отдельности — оно роняет весь экран в «HTTP 400 Bad
    # Request», и по этому тексту причину не угадать.
    длинные = []
    исходный_say = bot.say
    собранное = {}
    текущая = {"кнопка": None}

    def перехват(chat, text, inline=None, keys=True):
        for ряд in (inline or []):
            for к in ряд:
                cd = к.get("callback_data", "")
                if len(cd.encode()) > 64:
                    длинные.append(cd)
        отправлено.append(text)
        собранное.setdefault(текущая["кнопка"], []).append((text, inline or []))

    bot.say = перехват

    ошибки, медленные, ждут_ответа = [], [], set()
    for кнопка, экран in bot.BUTTONS.items():
        отправлено.clear()
        bot._await.pop(ТЕСТОВЫЙ_ЧАТ, None)
        текущая["кнопка"] = кнопка
        t = time.time()
        беда = None
        try:
            экран(ТЕСТОВЫЙ_ЧАТ)
            if not отправлено:
                беда = "ничего не ответил"
        except Exception as e:
            беда = f"{type(e).__name__}: {e}"
        сколько = time.time() - t
        if bot._await.pop(ТЕСТОВЫЙ_ЧАТ, None):
            ждут_ответа.add(кнопка)
        if беда:
            ошибки.append((кнопка, беда))
        if сколько > 5:
            медленные.append((кнопка, сколько))
        print(f"  {'❌' if беда else '✅'} {кнопка:<24} {сколько:>5.1f}с", flush=True)

    print(f"\nэкранов: {len(bot.BUTTONS)}")
    if медленные:
        print("дольше 5 секунд:")
        for к, с in sorted(медленные, key=lambda x: -x[1]):
            print(f"   {к:<24} {с:.1f}с")
    if длинные:
        print(f"\n❌ callback_data длиннее 64 байт: {len(длинные)}")
        for cd in длинные[:5]:
            print(f"   {len(cd.encode())} байт: {cd[:70]}")
        return 1
    if ошибки:
        print("\n❌ СЛОМАНЫ:")
        for к, e in ошибки:
            print(f"   {к:<24} {e[:100]}")
        return 1
    беды = проверки_тз(собранное, ждут_ответа)
    if беды:
        print(f"\n❌ нарушены требования ТЗ: {len(беды)}")
        for b in беды[:15]:
            print(f"   {b}")
        return 1
    print("\n✅ все экраны отвечают · требования ТЗ соблюдены")
    return 0


if __name__ == "__main__":
    sys.exit(main())


