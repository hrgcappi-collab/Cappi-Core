"""Итоги недели уходят в понедельник в 9:00 — и за ту неделю, которая закрылась.

Ошибка в выборе недели не падает и не видна в логе: отчёт уходит
вовремя, выглядит нормально и содержит числа позапрошлой недели. В
понедельник хватало бы `неделя.прошлая()` — в воскресенье она отдаёт
неделю на семь дней раньше нужной. День отправки переносили уже дважды
(понедельник → воскресенье 23:00 → понедельник 9:00), поэтому правило
проверяем по всем семи дням, а не только по дню отправки.

И отдельно сторожим главное свойство нового времени: неделя к моменту
отправки должна быть закрыта целиком. В воскресенье в 23:00 она не была
— не хватало заказов после одиннадцати и закрытия смены в три ночи, и
процент плана уходил заниженным.

Заодно сторожим, что расходы ИИ не поехали вслед за итогами: у них свой
день и своё время, и однажды они делили одну константу.
"""
import sys; sys.path.insert(0, '.')
from datetime import date, timedelta

import bot
import неделя

ПРОВАЛ = []


def ждём(когда, ждали_с, ждали_по, почему):
    с, по = bot._неделя_к_отправке(когда)
    ок = (с, по) == (ждали_с, ждали_по)
    print(f"  {'OK ' if ок else '❌ '} {когда} {'пн вт ср чт пт сб вс'.split()[когда.weekday()]}"
          f" → {с}..{по}   {почему}")
    if not ок:
        ПРОВАЛ.append(f"{когда}: ждали {ждали_с}..{ждали_по}, получили {с}..{по}")


print("какую неделю отдаёт правило")
# Опорная неделя: 26.10.2026 (пн) – 01.11.2026 (вс).
пн, вс = date(2026, 10, 26), date(2026, 11, 1)
ждём(вс, пн, вс, "воскресенье — закрывается текущая неделя")
for сдвиг, имя in ((1, "понедельник"), (2, "вторник"), (3, "среда"),
                   (4, "четверг"), (5, "пятница"), (6, "суббота")):
    ждём(вс + timedelta(days=сдвиг), пн, вс, f"{имя} — закрылась предыдущая")

# Своё расписание у каждой рассылки.
print("\nрасписание")
проверки = [
    ("НЕДЕЛЯ_ДЕНЬ", bot.НЕДЕЛЯ_ДЕНЬ, 0, "итоги недели — понедельник"),
    ("НЕДЕЛЯ_В", bot.НЕДЕЛЯ_В, "09:00", "итоги недели — 9:00 по Киеву"),
    ("РАСХОДЫ_ДЕНЬ", bot.РАСХОДЫ_ДЕНЬ, 0, "расходы ИИ — понедельник"),
    ("РАСХОДЫ_В", bot.РАСХОДЫ_В, "10:00", "расходы ИИ — 10:00"),
]
for имя, факт, ждали, почему in проверки:
    ок = факт == ждали
    print(f"  {'OK ' if ок else '❌ '} {имя} = {факт!r}   {почему}")
    if not ок:
        ПРОВАЛ.append(f"{имя}: ждали {ждали!r}, в коде {факт!r}")

# Константы не должны снова оказаться одной и той же величиной: именно
# это и связывало две рассылки.
if (bot.НЕДЕЛЯ_ДЕНЬ, bot.НЕДЕЛЯ_В) == (bot.РАСХОДЫ_ДЕНЬ, bot.РАСХОДЫ_В):
    ПРОВАЛ.append("итоги недели и расходы ИИ опять в одно время")

# Правило обязано совпадать с `границы()` для воскресенья: если кто-то
# поменяет нарезку недели, тест должен это заметить здесь, а не в чате.
print("\nсогласие с неделя.границы()")
for сдвиг in range(-21, 8):
    д = вс + timedelta(days=сдвиг)
    если = bot._неделя_к_отправке(д)
    гр = неделя.границы(если[0])
    if гр != если:
        ПРОВАЛ.append(f"{д}: правило отдало {если}, а границы() — {гр}")
print(f"  проверено дней: 29, расхождений: "
      f"{len([p for p in ПРОВАЛ if 'границы' in p])}")

# Неделя к моменту отправки должна быть закрыта целиком: иначе цифры
# занижены, а процент плана читается как итог. Если день отправки опять
# унесут внутрь недели, тест покраснеет — и вместе с ним надо вернуть
# оговорку «воскресенье ещё не закрыто» в `_send_weekly`.
print("\nнеделя закрыта к моменту отправки")
for сдвиг in range(0, 7):
    д = вс + timedelta(days=сдвиг)
    if д.weekday() != bot.НЕДЕЛЯ_ДЕНЬ:
        continue
    _, по = bot._неделя_к_отправке(д)
    ок = по < д
    print(f"  {'OK ' if ок else '❌ '} отправка {д} {bot.НЕДЕЛЯ_В}"
          f" → неделя кончилась {по}")
    if not ок:
        ПРОВАЛ.append(f"{д}: неделя кончается {по}, то есть не закрыта к отправке")

print("\nПРОВАЛОВ:", len(ПРОВАЛ))
for p in ПРОВАЛ:
    print("   ", p)
sys.exit(1 if ПРОВАЛ else 0)
