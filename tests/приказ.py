"""Тело приказа о цене — сверено с живым документом Syrve, без отправки.

Единственное необратимое действие бота ничем не проверялось, кроме
«без права не вызывается». Регрессия в составе документа — не то поле,
не тот формат даты, лишний ключ — доехала бы до боевого приказа.

Образец — приказ 0091 от 10.09.2026, снятый с сервера (`backup-prikaz-
0091.json`): Syrve сам присваивает `id`, `documentNumber` и `num`, всё
остальное обязано совпасть буква в букву.
"""
import sys; sys.path.insert(0, '.')
import cappi

ОДЕССА = "427d6dd2-1d65-275f-014c-ec534e53000d"
ДНЕПР = "4d11b241-0000-0000-0000-000000000000"
ОБРАЗЕЦ = {
    "dateIncoming": "2026-09-10", "status": "PROCESSED",
    "deletePreviousMenu": False, "dateTo": "2500-01-01",
    "items": [{
        "departmentId": ОДЕССА, "productId": "caf90069-4972-45ab-9b94-84ca91034590",
        "productSizeId": None, "including": True, "price": 45,
        "taxCategoryId": None, "taxCategoryEnabled": False, "dishOfDay": False,
        "flyerProgram": False, "pricesForCategories": [], "includeForCategories": [],
    }],
}

cappi.отдел = lambda: ОДЕССА
s = cappi.Syrve.__new__(cappi.Syrve)
s.host, s.key = "https://stub", "k"
отправлено = []
s._send = lambda body: отправлено.append(body) or {"id": "x"}
провалы = 0

# 1. Одна позиция — тело как у живого приказа.
s.create_price_order("caf90069-4972-45ab-9b94-84ca91034590", ОДЕССА, 45, "2026-09-10")
if отправлено[-1] != ОБРАЗЕЦ:
    провалы += 1
    print("❌ тело одиночного приказа разошлось с образцом:")
    for k in set(ОБРАЗЕЦ) | set(отправлено[-1]):
        if ОБРАЗЕЦ.get(k) != отправлено[-1].get(k):
            print(f"   {k}: ждали {ОБРАЗЕЦ.get(k)!r}, получили {отправлено[-1].get(k)!r}")
else:
    print("✅ одиночный приказ — как живой 0091")

# 2. Список — один документ, строки в том же порядке, та же форма строки.
строки = [{"pid": f"p{i}", "dep": ОДЕССА, "price": 100 + i} for i in range(3)]
s.create_price_order(строки, "2026-09-11")
тело = отправлено[-1]
if len(отправлено) != 2 or len(тело["items"]) != 3 \
        or [i["price"] for i in тело["items"]] != [100, 101, 102] \
        or set(тело["items"][0]) != set(ОБРАЗЕЦ["items"][0]):
    провалы += 1; print("❌ список не ушёл одним документом в форме образца")
else:
    print("✅ список из трёх — один документ, три строки")

# 3. Днепр — отказ до отправки.
было = len(отправлено)
try:
    s.create_price_order("p", ДНЕПР, 10, "2026-09-11")
    провалы += 1; print("❌ приказ в чужое подразделение ушёл")
except cappi.ЧужойОтдел:
    print("✅ чужое подразделение — отказ" if len(отправлено) == было
          else "❌ отказ был, но отправка случилась")
    провалы += len(отправлено) != было

# 4. Конфликт по дате — ничего не проводится, даже если конфликт в одной строке.
s.orders = lambda a, b: [{"documentNumber": "0099",
                          "items": [{"productId": "p1", "departmentId": ОДЕССА}]}]
было = len(отправлено)
try:
    s.set_prices(строки, "2026-09-12")
    провалы += 1; print("❌ конфликт приказов не остановил пачку")
except cappi.PriceOrderExists as e:
    print("✅ конфликт по одной строке — не проводится ничего"
          if len(отправлено) == было else "❌ часть пачки ушла")
    провалы += len(отправлено) != было

print(f"\n{'❌ ПРОВАЛОВ: %d' % провалы if провалы else '✅ тело приказа в порядке'}")
sys.exit(1 if провалы else 0)
