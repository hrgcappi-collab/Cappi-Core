"""Заливка в книгу заказчика: что именно уходит в какой столбец.

Офлайн: Syrve и Apps Script подменены, сеть не нужна.

Зачем тест. 11.10.2026 недельные строки десять дней слались с дневной
картой столбцов. Ключ находился, скрипт отвечал «записано», список
ненайденных был пуст — и выручка Лазаревой ложилась в «% опер», а столбец
«Факт» оставался пустым. Ни один сигнал не сработал, потому что проверять
было нечем.

Правило пишем здесь прямо, литералами, а не через константы модуля:
иначе тест повторит ту же ошибку, что и код.
"""
import sys
sys.path.insert(0, '.')
import datetime as dt

import таблица
import report

ДЕНЬ = dt.date(2026, 10, 6)          # понедельник второй недели октября
ВЫРУЧКА = {"Лазарева": 60000.0, "Левітана": 40000.0}

отправлено = []
таблица._послать = lambda тело, timeout=120: (
    отправлено.append(тело) or {"записано": 0, "ненайдены": [], "лист": "План-факт"})
таблица.настроена = lambda: True
таблица._факт = lambda дни: {д: dict(ВЫРУЧКА) for д in дни}
report.выручка_пиу = lambda s, с, по: {"всего": sum(ВЫРУЧКА.values()),
                                       "точки": dict(ВЫРУЧКА)}


class _ЗаглушкаSyrve:
    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


таблица.cappi.Syrve = _ЗаглушкаSyrve
report.plan_for = lambda д, вид="опер": (50000 if вид == "опер" else 55000, None)

провал = []


def проверить(условие, что):
    ок = bool(условие)
    print(f"  {'✅' if ок else '❌'} {что}")
    if not ок:
        провал.append(что)
    return ок


таблица.залить([ДЕНЬ])
if not отправлено:
    print("❌ ничего не отправлено")
    sys.exit(1)
строки = отправлено[0]["строки"]
дневные = [с for с in строки if с["ключ"] == "06.10"]
недельные = [с for с in строки if с["ключ"].endswith("нед")]

print("отправлено строк:", len(строки))
for с in строки:
    print(f"   {с['ключ']:<10} {с['значения']}")

print("\nдень:")
проверить(len(дневные) == 1, "одна строка на день")
d = дневные[0]["значения"] if дневные else {}
проверить(d.get("7") == 60000, "Лазарева в столбец 7")
проверить(d.get("8") == 40000, "Левітана в столбец 8")
проверить(d.get("9") == 100000, "сеть в столбец 9")
проверить(d.get("10") == 200, "% опер в столбец 10, целым числом")
проверить(d.get("11") == 182, "% админ в столбец 11, целым числом")
проверить(set(d) == {"7", "8", "9", "10", "11"}, "у дня ровно пять столбцов")

print("\nнеделя:")
проверить(bool(недельные), "недельные строки есть")
for с in недельные:
    v = с["значения"]
    имя = с["ключ"]
    проверить(v.get("6") == 100000, f"{имя}: факт сети в столбец 6")
    проверить("7" in v and isinstance(v["7"], int), f"{имя}: % опер в столбец 7")
    проверить("8" in v and isinstance(v["8"], int), f"{имя}: % админ в столбец 8")
    проверить(v.get("9") == "" and v.get("10") == "" and v.get("11") == "",
              f"{имя}: столбцы 9–11 чистятся")
    проверить(not any(k in v and v[k] not in ("",) and k in ("9", "10", "11")
                      for k in ("9", "10", "11")),
              f"{имя}: в 9–11 не уходит выручка")

print("\nключи:")
проверить(all(len(с["ключ"]) == 5 and с["ключ"][2] == "." for с in дневные),
          "ключ дня в виде дд.мм")
проверить(all(с["ключ"].split()[0].isdigit() for с in недельные),
          "ключ недели в виде «N нед»")

print("\nбудущее:")
отправлено.clear()
таблица.залить([dt.date.today() + dt.timedelta(days=3)])
проверить(not отправлено, "день из будущего не отправляется")

print(f"\nПРОВАЛОВ: {len(провал)}" + ("" if not провал else " — " + "; ".join(провал)))
sys.exit(1 if провал else 0)
