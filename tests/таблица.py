"""Заливка в книгу заказчика: что именно уходит в какой столбец.

Офлайн: Syrve и Apps Script подменены, сеть не нужна.

Устройство листа «План-факт», проверено по книге 12.10.2026:

    блок ПО ДНЯМ   A дата · B день · C–F планы по филиалам ·
                   G Факт Лаз · H Факт Лев · I Факт сеть · J % опер · K % админ
    строки «N нед» лежат ВНУТРИ этого блока как итог недели и имеют те же
                   столбцы, что и день
    блок НЕДЕЛИ    отдельная таблица выше, ключи «1 неделя» … «5 неделя»,
                   столбцы F Факт · G % опер · H % админ — бот её не пишет

11.10.2026 я решил, что «N нед» относится к блоку НЕДЕЛИ, и перенёс запись
в столбцы 6–8. Ключ находился, скрипт отвечал «записано» — и затёр
«План Лев адмін» и оба факта по филиалам в итоговых строках недель.
Тест закрепляет, что «N нед» пишется дневной картой.
"""
import sys
sys.path.insert(0, '.')
import datetime as dt

import таблица
import report

ДЕНЬ = dt.date(2026, 10, 6)
ВЫРУЧКА = {"Лазарева": 60000.0, "Левітана": 40000.0}

отправлено = []
таблица._послать = lambda тело, timeout=120: (
    отправлено.append(тело) or {"записано": 0, "ненайдены": [], "лист": "План-факт"})
таблица.настроена = lambda: True
таблица._факт = lambda дни: {д: dict(ВЫРУЧКА) for д in дни}
report.выручка_пиу = lambda s, с, по: {"всего": sum(ВЫРУЧКА.values()),
                                       "точки": dict(ВЫРУЧКА)}


class _ЗаглушкаSyrve:
    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


таблица.cappi.Syrve = _ЗаглушкаSyrve
report.plan_for = lambda д, вид="опер": (50000 if вид == "опер" else 55000, {}, "тест")

провал = []


def проверить(условие, что):
    ок = bool(условие)
    print(f"  {'✅' if ок else '❌'} {что}")
    if not ок:
        провал.append(что)
    return ок


таблица.залить([ДЕНЬ])
if not отправлено:
    print("❌ ничего не отправлено")
    sys.exit(1)
строки = отправлено[0]["строки"]
дневные = [с for с in строки if с["ключ"] == "06.10"]
недельные = [с for с in строки if с["ключ"].endswith("нед")]

print("отправлено строк:", len(строки))
for с in строки:
    print(f"   {с['ключ']:<10} {с['значения']}")

# Правило пишем литералами, а не через константы модуля: иначе тест
# повторит ту же ошибку, что и код, и останется зелёным.
print("\nдень:")
проверить(len(дневные) == 1, "одна строка на день")
d = дневные[0]["значения"] if дневные else {}
проверить(d.get("7") == 60000, "Лазарева в столбец 7")
проверить(d.get("8") == 40000, "Левітана в столбец 8")
проверить(d.get("9") == 100000, "сеть в столбец 9")
проверить(d.get("10") == 200, "% опер в столбец 10, целым числом")
проверить(d.get("11") == 182, "% админ в столбец 11, целым числом")
проверить(set(d) == {"7", "8", "9", "10", "11"}, "у дня ровно пять столбцов")

print("\nитог недели внутри дневного блока:")
проверить(bool(недельные), "недельные строки есть")
for с in недельные:
    v, имя = с["значения"], с["ключ"]
    проверить(v.get("7") == 60000, f"{имя}: Лазарева в столбец 7")
    проверить(v.get("8") == 40000, f"{имя}: Левітана в столбец 8")
    проверить(v.get("9") == 100000, f"{имя}: сеть в столбец 9")
    проверить(isinstance(v.get("10"), int), f"{имя}: % опер в столбец 10")
    проверить(isinstance(v.get("11"), int), f"{имя}: % админ в столбец 11")
    # Столбцы 1–6 — это дата, день и планы заказчика. Бот их не трогает:
    # «План Лев адмін» стоит в шестом, и запись туда стирает его насовсем.
    проверить(not ({"1", "2", "3", "4", "5", "6"} & set(v)),
              f"{имя}: столбцы 1–6 не трогаются")

print("\nключи:")
проверить(all(len(с["ключ"]) == 5 and с["ключ"][2] == "." for с in дневные),
          "ключ дня в виде дд.мм")
проверить(all(с["ключ"].split()[0].isdigit() and с["ключ"].endswith(" нед")
              for с in недельные), "ключ итога недели в виде «N нед»")

print("\nбудущее:")
отправлено.clear()
таблица.залить([dt.date.today() + dt.timedelta(days=3)])
проверить(not отправлено, "день из будущего не отправляется")

print(f"\nПРОВАЛОВ: {len(провал)}" + ("" if not провал else " — " + "; ".join(провал)))
sys.exit(1 if провал else 0)
