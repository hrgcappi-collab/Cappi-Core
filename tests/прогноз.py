"""Прогноз месяца: остаток считается по дням недели, недобор виден цифрой.

Прогноз — та цифра, по которой решают, добавлять ли неделю к плану, и
ошибка в нём не падает: отчёт уходит вовремя и выглядит правдоподобно.
Поэтому проверяем арифметику, а не наличие строк.

Три места, где легко соврать и не заметить:

  · остаток месяца, посчитанный средним днём вместо дней недели. Суббота
    даёт 180 тысяч, понедельник 107; месяц, в остатке которого три
    воскресенья, усреднённым днём занижается;
  · день простоя в окне усреднения. Если филиал стоял, его ноль тянет
    остаток вниз, и прогноз занижает месяц на настоящие деньги;
  · прогноз ниже плана при зелёном светофоре. Светофор красит по единому
    порогу (красное — ниже 85% плана), и на 97% он честно зелёный, поэтому
    недобор обязан стоять отдельной строкой.
"""
import sys; sys.path.insert(0, '.')
from datetime import date, timedelta

import report
import прогноз

ПРОВАЛ = []


def ждём(что, было, ждали, допуск=0.5):
    ок = abs(было - ждали) <= допуск
    print(f"  {'OK ' if ок else '❌ '} {что}: {было:,.1f} (ждали {ждали:,.1f})")
    if not ок:
        ПРОВАЛ.append(f"{что}: {было:,.1f} вместо {ждали:,.1f}")


def верно(что, условие):
    print(f"  {'OK ' if условие else '❌ '} {что}")
    if not условие:
        ПРОВАЛ.append(что)


# ── данные: будни по 100, выходные по 300, чтобы перекос был виден ──
ПО_ДНЯМ = {0: 100.0, 1: 100.0, 2: 100.0, 3: 100.0, 4: 300.0, 5: 300.0, 6: 300.0}


def поддельные_дни(с, по, нули=()):
    out = {}
    d = с
    while d <= по:
        выр = 0.0 if d in нули else ПО_ДНЯМ[d.weekday()]
        out[d] = {"выр": выр, "зак": выр / 10}
        d += timedelta(days=1)
    return out


def подменить(нули=()):
    прогноз._дни_продаж = lambda s, с, по: поддельные_дни(с, по, нули)
    прогноз.коэффициент = lambda s, сегодня: 1.0


# ── 1 · остаток по дням недели, а не средним днём ──
print("остаток месяца считается по дням недели")
подменить()
прогноз.план_периода = lambda с, по, вид="админ": 0.0
п = прогноз.месяц(None, date(2026, 11, 15))
# факт 01–14.11.2026: по два каждого дня недели → 4*2*100 + 3*2*300 = 2600
ждём("факт первых 14 дней", п["факт_прод"], 2600)
# остаток 15–30.11: вс,пн,вт,ср,чт,пт,сб ×2 плюс ещё вс и пн
остаток = sum(ПО_ДНЯМ[(date(2026, 11, д)).weekday()] for д in range(15, 31))
ждём("остаток по дням недели", п["прогноз_прод"] - п["факт_прод"], остаток)
ждём("прогноз месяца", п["прогноз_прод"], 2600 + остаток)
средним_днём = п["факт_прод"] / 14 * 30
верно("по дням недели и средним днём числа разные — перекос виден",
       abs(п["прогноз_прод"] - средним_днём) > 1)

# ── 2 · день простоя выброшен из усреднения ──
print("\nдень простоя не тянет остаток вниз")
простой = date(2026, 11, 7)                     # суббота, обычно 300
подменить(нули=(простой,))
п2 = прогноз.месяц(None, date(2026, 11, 15))
верно("простой посчитан фактом, а не средним", п2["факт_прод"] == 2600 - 300)
ждём("остаток не просел", п2["прогноз_прод"] - п2["факт_прод"], остаток)
верно("простой отмечен в расчёте", п2["выброшено_простоев"] == 1)

# ── 3 · месяц только начался ──
print("\nраньше третьего числа прогноза нет")
подменить()
for день in (1, 2, 3):
    п3 = прогноз.месяц(None, date(2026, 11, день))
    мало = bool(п3.get("мало_данных"))
    верно(f"{день}-е число → {'без прогноза' if мало else 'прогноз есть'}",
           мало is (день <= 3))

# ── 4 · план: оба филиала и откат на оперативный ──
print("\nплан: два филиала и откат с админского на оперативный")
прогноз.план_периода = прогноз.__dict__["план_периода"]
import importlib
importlib.reload(прогноз)
подменить()
report.load_plan = lambda: {
    "weekly_admin": {"Зал Лазарева": {"2026-11-01": 1000.0}},
    "weekly": {"Зал Лазарева": {"2026-11-01": 700.0, "2026-11-02": 500.0},
               "Зал Левитана": {"2026-11-01": 300.0, "2026-11-02": 400.0}},
}
ждём("1.11 админский: 1000 своих + 300 откатом",
     прогноз.план_периода(date(2026, 11, 1), date(2026, 11, 1), "админ"), 1300)
ждём("2.11 админского нет вовсе → оба откатом",
     прогноз.план_периода(date(2026, 11, 2), date(2026, 11, 2), "админ"), 900)
ждём("оперативный считает только свой раздел",
     прогноз.план_периода(date(2026, 11, 1), date(2026, 11, 2), "опер"), 1900)

# ── 5 · что видит человек ──
print("\nстроки блока")
основа = {"с": date(2026, 11, 1), "по": date(2026, 11, 30),
          "закрыт": date(2026, 11, 14), "дней_закрыто": 14, "дней_всего": 30,
          "дней_осталось": 16, "выброшено_простоев": 0, "коэф": 1.03,
          "факт_прод": 1_949_228.0, "факт_зак": 1632, "факт_пиу": 2_012_369.0,
          "прогноз_прод": 4_162_651.0, "прогноз_пиу": 4_298_571.0,
          "прогноз_зак": 3524, "темп_пиу": 143_740.6,
          "план_на_сейчас": 2_038_142.0}

ниже = dict(основа, план=4_400_000.0, доля=4_298_571.0 / 4_400_000.0,
            нужно_в_день=(4_400_000.0 - 2_012_369.0) / 16)
текст = "\n".join(прогноз.строки(ниже))
верно("при прогнозе ниже плана есть строка недобора", "Недобор к плану" in текст)
верно("недобор посчитан в гривнах", report.money(4_400_000 - 4_298_571) in текст)
верно("светофор стоит — цель есть",
       any(з in текст for з in ("🟢", "🟡", "🔴")))

выше = dict(основа, план=4_000_000.0, доля=4_298_571.0 / 4_000_000.0,
            нужно_в_день=(4_000_000.0 - 2_012_369.0) / 16)
верно("при перевыполнении строки недобора нет",
       "Недобор" not in "\n".join(прогноз.строки(выше)))

без = dict(основа, план=0.0, доля=None, нужно_в_день=0.0)
т_без = "\n".join(прогноз.строки(без))
верно("без плана светофора нет — знак без цели это украшение",
       not any(з in т_без for з in ("🟢", "🟡", "🔴")))
верно("без плана так и сказано", "Плана на месяц нет" in т_без)

для_всех = [текст, "\n".join(прогноз.строки(выше)), т_без,
            "\n".join(прогноз.строки({"мало_данных": True, "с": date(2026, 12, 1),
                                      "по": date(2026, 12, 31),
                                      "закрыт": date(2026, 11, 30), "надо_дней": 3}))]
верно("ни в одном случае не вылезает None или nan",
       not any(("None" in т) or ("nan" in т.lower()) for т in для_всех))

print("\nПРОВАЛОВ:", len(ПРОВАЛ))
for p in ПРОВАЛ:
    print("   ", p)
sys.exit(1 if ПРОВАЛ else 0)
