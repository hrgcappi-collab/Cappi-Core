"""Прогноз выручки месяца по текущему темпу. Только чтение.

Нужен потому, что до конца месяца никто не знает, выйдем ли на план, а
узнавать об этом первого числа поздно: поправить уже нечего. Блок уходит в
понедельничную сводку.

Две вещи, из-за которых это не делается в одну строку.

**Темп виден только по продажам, а план — в выручке ПиУ.** Глово заводят в
проводки одной суммой за месяц (31.10.2026 — 793 340 ₴, и встречная строка
−565 898 ₴ тем же днём), поэтому недельная и дневная выручка по ПиУ — мусор,
а внутри месяца этих денег там ещё нет вовсе. Поэтому считаем по продажам
OLAP, где каждый день честный, и переводим в ПиУ коэффициентом по трём
закрытым месяцам. За июль–октябрь 2026 он держался 1,031–1,036.

**Остаток месяца считается по дням недели, а не средним днём.** Суббота
даёт 180 тысяч, понедельник — 107; месяц, в остатке которого три воскресенья
и три понедельника, усреднённым днём считается неверно. Разница в ноябре
2026 вышла небольшой, потому что лишние воскресенье и понедельник погасили
друг друга, но это совпадение, а не правило.
"""
import statistics as st
from calendar import monthrange
from datetime import date, timedelta

import report

ОКНО_НЕДЕЛЬ = 5         # на чём усредняем дни недели
МЕСЯЦЕВ_НА_КОЭФ = 3     # сколько закрытых месяцев берём на коэффициент ПиУ
МИН_ДНЕЙ = 3            # раньше третьего числа темп — это шум, а не темп
ПРОСТОЙ = 0.5           # день ниже половины медианы в расчёт не берём


def _последний_закрытый(сегодня):
    """Вчера. Сегодняшняя смена ещё открыта: касса закрывается около 3:00."""
    return сегодня - timedelta(days=1)


def _конец_месяца(день):
    return date(день.year, день.month, monthrange(день.year, день.month)[1])


def _дни_продаж(s, с, по):
    """{дата: {«выр», «зак»}} по нашим филиалам. Границы включительные."""
    r = report.свободный_запрос(s, ["OpenDate.Typed", "Conception"],
                                ["DishDiscountSumInt", "UniqOrderId"], с, по)
    out = {}
    for x in r["строки"]:
        if not report.КОНЦЕПЦИИ.get(str(x.get("Conception"))):
            continue
        d = date.fromisoformat(str(x.get("OpenDate.Typed"))[:10])
        a = out.setdefault(d, {"выр": 0.0, "зак": 0})
        a["выр"] += x.get("DishDiscountSumInt") or 0
        a["зак"] += x.get("UniqOrderId") or 0
    return out


def коэффициент(s, сегодня):
    """Во сколько раз выручка ПиУ больше продаж OLAP, по закрытым месяцам.

    Берём три месяца и среднее: за год коэффициент сполз с 1,002 до 1,036,
    поэтому медиана по всему году занижала бы прогноз примерно на процент.
    """
    ряд = []
    месяц = сегодня.replace(day=1)
    for _ in range(МЕСЯЦЕВ_НА_КОЭФ):
        месяц = (месяц - timedelta(days=1)).replace(day=1)
        последний = _конец_месяца(месяц)
        прод = sum(v["выр"] for v in _дни_продаж(s, месяц, последний).values())
        пиу = report.выручка_пиу(s, месяц, последний)["всего"]
        if прод > 0 and пиу > 0:
            ряд.append(пиу / прод)
    return st.mean(ряд) if ряд else 1.0


def план_периода(с, по, вид="админ"):
    """Сумма дневных планов за период, по обоим филиалам.

    Порядок тот же, что в недельной сводке: свой вид плана, откат на
    оперативный. Иначе один и тот же вопрос получал бы два разных ответа.
    """
    p = report.load_plan()
    свой = report._раздел(p, вид, report.ДЕНЬ)
    опер = report._раздел(p, "опер", report.ДЕНЬ)
    всего = 0.0
    d = с
    while d <= по:
        for ключ in report.ТОЧКИ:
            v = (свой.get(ключ) or {}).get(d.isoformat())
            if v is None:
                v = (опер.get(ключ) or {}).get(d.isoformat())
            if v:
                всего += v
        d += timedelta(days=1)
    return всего


def месяц(s, сегодня=None, вид="админ"):
    """Прогноз текущего месяца. Деньги — в выручке ПиУ, как план."""
    сегодня = сегодня or date.today()
    первое = сегодня.replace(day=1)
    последний = _конец_месяца(сегодня)
    закрыт = _последний_закрытый(сегодня)
    if (закрыт - первое).days + 1 < МИН_ДНЕЙ:
        return {"мало_данных": True, "с": первое, "по": последний,
                "закрыт": закрыт, "надо_дней": МИН_ДНЕЙ}

    дни = _дни_продаж(s, первое - timedelta(weeks=ОКНО_НЕДЕЛЬ), закрыт)
    факт = {d: v for d, v in дни.items() if первое <= d <= закрыт}
    if not факт:
        return {"мало_данных": True, "с": первое, "по": последний,
                "закрыт": закрыт, "надо_дней": МИН_ДНЕЙ}

    # Средние по дням недели — на окне, из которого выброшены простои:
    # день, когда филиал стоял, тянет остаток месяца вниз без причины.
    окно = {d: v for d, v in дни.items()
            if закрыт - timedelta(days=ОКНО_НЕДЕЛЬ * 7 - 1) <= d <= закрыт}
    медиана = st.median([v["выр"] for v in окно.values()]) if окно else 0
    живые = {d: v for d, v in окно.items() if v["выр"] >= медиана * ПРОСТОЙ}
    по_дням = {}
    for d, v in живые.items():
        по_дням.setdefault(d.weekday(), []).append(v)
    средний_день = st.mean([v["выр"] for v in живые.values()]) if живые else 0
    средний_зак = st.mean([v["зак"] for v in живые.values()]) if живые else 0

    остаток = [закрыт + timedelta(days=i)
               for i in range(1, (последний - закрыт).days + 1)]
    ост_прод = ост_зак = 0.0
    for d in остаток:
        свои = по_дням.get(d.weekday())
        ост_прод += st.mean([v["выр"] for v in свои]) if свои else средний_день
        ост_зак += st.mean([v["зак"] for v in свои]) if свои else средний_зак

    К = коэффициент(s, сегодня)
    факт_прод = sum(v["выр"] for v in факт.values())
    факт_зак = sum(v["зак"] for v in факт.values())
    прогноз_прод = факт_прод + ост_прод
    план = план_периода(первое, последний, вид)
    факт_пиу = факт_прод * К
    прогноз_пиу = прогноз_прод * К
    нужно = ((план - факт_пиу) / len(остаток)) if остаток and план else 0
    return {
        "с": первое, "по": последний, "закрыт": закрыт,
        "дней_закрыто": len(факт), "дней_всего": последний.day,
        "дней_осталось": len(остаток), "выброшено_простоев": len(окно) - len(живые),
        "коэф": К,
        "факт_прод": факт_прод, "факт_зак": факт_зак, "факт_пиу": факт_пиу,
        "прогноз_прод": прогноз_прод, "прогноз_пиу": прогноз_пиу,
        "прогноз_зак": round(факт_зак + ост_зак),
        "темп_пиу": факт_пиу / len(факт),
        "план": план, "план_на_сейчас": план_периода(первое, закрыт, вид),
        "доля": (прогноз_пиу / план) if план else None,
        "нужно_в_день": нужно,
    }


def строки(п):
    """Блок для понедельничной сводки. Светофор ставим: цель есть — это план."""
    if п.get("мало_данных"):
        return [f"📈 <b>Прогноз месяца</b>",
                f"Месяц только начался — посчитаю с {п['надо_дней'] + 1}-го числа."]
    out = ["📈 <b>Прогноз месяца</b>",
           f"Факт {п['с']:%d.%m}–{п['закрыт']:%d.%m} · "
           f"{report.money(п['факт_пиу'])} ₴ "
           f"(по {report.money(п['темп_пиу'])} ₴ в день)"]
    if п["план"]:
        знак = report.цвет(п["доля"], report.КРАСНОЕ["выручка"], False)
        проц = f"{п['доля'] * 100:.1f}".replace(".", ",")
        out += [f"Прогноз · <b>{report.money(п['прогноз_пиу'])} ₴</b>",
                f"{знак} План {report.money(п['план'])} ₴ — {проц}%"]
        out.append(f"На остаток {п['дней_осталось']} дн нужно по "
                   f"{report.money(п['нужно_в_день'])} ₴ в день, "
                   f"идём по {report.money(п['темп_пиу'])}")
        # Светофор красит по единому порогу (красное — ниже 85% плана), и на
        # 97% он честно зелёный. Но прогноз ниже плана — это недобор, и он
        # обязан стоять цифрой, а не читаться из цвета.
        if п["доля"] < 1:
            out.append(f"Недобор к плану · "
                       f"{report.money(п['план'] - п['прогноз_пиу'])} ₴")
    else:
        out += [f"Прогноз · <b>{report.money(п['прогноз_пиу'])} ₴</b>",
                "Плана на месяц нет — сравнивать не с чем."]
    out.append(f"<i>Заказов к концу месяца · около {п['прогноз_зак']}</i>")
    if п["выброшено_простоев"]:
        out.append(f"<i>Из расчёта выброшено дней с простоем: "
                   f"{п['выброшено_простоев']}</i>")
    return out


def блок(сегодня=None, вид="админ"):
    """Готовые строки для сводки. Свою сессию открывает сам."""
    import cappi
    with cappi.Syrve() as s:
        return строки(месяц(s, сегодня, вид))
