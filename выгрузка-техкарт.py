#!/usr/bin/env python3
"""Выгрузка техкарт: состав и себестоимость всего, у чего есть карта.

Запускать на машине, где есть ~/.cappi/api.env и доступ к Syrve:

    python3 выгрузка-техкарт.py

Кладёт два файла в выгрузка/ — как и остальные отчёты, в репозиторий
они не попадают.

    07-техкарты.csv   по блюду: себестоимость, цена, фудкост, маржа
    08-состав.csv     построчно: каждый ингредиент каждой карты

Цены берутся из Cloud API (то, что видит гость). Себестоимость считает
cost.py — тем же способом, которым её считает бот, сверенным с колонкой
Syrve Office.
"""
import csv
import sys

import cappi
import cost

ТИПЫ = ("DISH", "PREPARED", "MODIFIER")


def писать(имя, поля, строки):
    путь = f"выгрузка/{имя}"
    with open(путь, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=поля, delimiter=";")
        w.writeheader()
        w.writerows(строки)
    print(f"    {путь}: строк {len(строки)}")


def main():
    print("Тяну техкарты, остатки и номенклатуру…")
    д = cost._данные(обновить=True)
    карты, товары = д["карта"], д["товары"]
    print(f"    карт {len(карты)}, позиций {len(товары)}, "
          f"цен единицы {len(д['цена'])}")

    try:
        цены = cappi.cloud_prices()
    except Exception as e:
        print(f"    ! цены из Cloud API не пришли ({e}) — колонка будет пустой")
        цены = {}

    блюда, состав = [], []
    без_карты = 0
    for pid, карта in карты.items():
        товар = товары.get(pid)
        if not товар or товар.get("type") not in ТИПЫ:
            continue
        r = cost.блюда(pid)
        if not r:
            без_карты += 1
            continue
        арт = str(товар.get("num"))
        ц = (цены.get(арт) or {}).get("price")
        сс = r["итого"]
        блюда.append({
            "артикул": арт,
            "блюдо": товар.get("name"),
            "тип": товар.get("type"),
            "категория": (товар.get("category") or ""),
            "выход": round(r.get("выход") or 1, 3),
            "ингредиентов": len(r["строки"]),
            "себестоимость": round(сс, 2),
            "цена": ц if ц is not None else "",
            "фудкост_%": round(cost.фудкост(сс, ц), 1) if ц else "",
            "маржа": round(ц - сс, 2) if ц else "",
            "дыры": ", ".join(dict.fromkeys(r["дыры"])),
        })
        for с in r["строки"]:
            состав.append({
                "артикул_блюда": арт,
                "блюдо": товар.get("name"),
                "ингредиент": с["название"],
                "количество": round(с["кол"], 4),
                "за_единицу": round(с["за_единицу"], 4) if с["за_единицу"] is not None else "",
                "сумма": round(с["сумма"], 2) if с["сумма"] is not None else "",
                "доля_%": (round(с["сумма"] / сс * 100, 1)
                           if с["сумма"] is not None and сс else ""),
            })

    блюда.sort(key=lambda x: x["блюдо"] or "")
    состав.sort(key=lambda x: (x["блюдо"] or "", -(x["сумма"] or 0)))

    писать("07-техкарты.csv",
           ["артикул", "блюдо", "тип", "категория", "выход", "ингредиентов",
            "себестоимость", "цена", "фудкост_%", "маржа", "дыры"], блюда)
    писать("08-состав.csv",
           ["артикул_блюда", "блюдо", "ингредиент", "количество",
            "за_единицу", "сумма", "доля_%"], состав)

    с_ценой = [b for b in блюда if b["цена"] != ""]
    дырявых = [b for b in блюда if b["дыры"]]
    print(f"\nГотово. Блюд с картой {len(блюда)}, из них с ценой {len(с_ценой)}.")
    if дырявых:
        print(f"У {len(дырявых)} позиций часть ингредиентов без цены — "
              f"их себестоимость занижена, колонка «дыры» показывает какие.")


if __name__ == "__main__":
    sys.exit(main())
