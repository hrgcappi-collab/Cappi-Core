import sys
import os
"""Событийный разбор: что стало со спросом вокруг каждой смены цены.

Считаем «до» и «после» по окнам в четыре недели, переходную неделю
выбрасываем, и вычитаем то же изменение по всем блюдам, которых цена
в это время не касалась, — иначе сезон запишется в эластичность.
"""
import json, math, datetime as dt, collections, sys, statistics
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from мнк import мнк
import os
S = sys.argv[1] if len(sys.argv) > 1 else "/tmp/эластичность"  # куда тяга.py сложила выгрузку
d = json.load(open(f"{S}/панель2.json"))
панель, имена, кат = d["панель"], d["имена"], d["категории"]
ОКНО, ЗАЗОР = 4, 1


def ряды(к):
    w = sorted(панель[к])
    return w, {x: панель[к][x] for x in w}


ВСЕ_НЕДЕЛИ = sorted({w for x in панель.values() for w in x})
ИНДЕКС = {w: i for i, w in enumerate(ВСЕ_НЕДЕЛИ)}


def уровни(к):
    """Ступени цены: (индекс_начала, индекс_конца, цена)."""
    w, r = ряды(к)
    шаги = []
    for x in w:
        ц = r[x]["мода"]
        if ц <= 0:
            continue
        if шаги and abs(ц / шаги[-1][2] - 1) < 0.005:
            шаги[-1][1] = ИНДЕКС[x]
        else:
            шаги.append([ИНДЕКС[x], ИНДЕКС[x], ц])
    return шаги


постоянные, временные = [], []
for к in панель:
    if len(панель[к]) < 20:
        continue
    ср = sum(v["шт"] for v in панель[к].values()) / len(панель[к])
    if ср < 2:
        continue
    ш = уровни(к)
    for i in range(1, len(ш)):
        было, стало = ш[i - 1], ш[i]
        длина_до = было[1] - было[0] + 1
        длина_после = стало[1] - стало[0] + 1
        шаг = math.log(стало[2] / было[2])
        общее = {"код": к, "имя": имена.get(к, к), "кат": кат.get(к, "—"),
                 "неделя": ВСЕ_НЕДЕЛИ[стало[0]], "i": стало[0],
                 "p0": было[2], "p1": стало[2], "шаг": шаг,
                 "чистое": list(панель[к].values())[0].get("чистое", False)}
        if длина_до >= 3 and длина_после >= 3:
            постоянные.append(общее)
        elif длина_после <= 2 and длина_до >= 3 and i + 1 < len(ш) \
                and abs(ш[i + 1][2] / было[2] - 1) < 0.02:
            общее["длина"] = длина_после
            временные.append(общее)

print(f"постоянных смен цены: {len(постоянные)}   "
      f"временных (акция с возвратом): {len(временные)}")


def объём(к, a, b):
    """Средние штуки за недели [a, b] по индексам."""
    w, r = ряды(к)
    шт = [r[x]["шт"] for x in w if a <= ИНДЕКС[x] <= b]
    return sum(шт) / len(шт) if len(шт) >= max(2, (b - a + 1) // 2) else None


def изменение(к, i, сдвиг=0):
    до = объём(к, i - ОКНО - ЗАЗОР + сдвиг, i - ЗАЗОР - 1 + сдвиг)
    после = объём(к, i + сдвиг, i + ОКНО - 1 + сдвиг)
    if not до or not после:
        return None
    return math.log(после / до)


# Блюда, которых цена не касалась в окне — это и есть фон.
менялась = collections.defaultdict(set)
for с in постоянные + временные:
    for j in range(с["i"] - ОКНО - 2, с["i"] + ОКНО + 2):
        менялась[с["код"]].add(j)


def фон(i, сдвиг=0):
    знач = []
    for к in панель:
        if any(j in менялась[к] for j in range(i - ОКНО - 2, i + ОКНО + 2)):
            continue
        if len(панель[к]) < 20:
            continue
        x = изменение(к, i, сдвиг)
        if x is not None:
            знач.append(x)
    return statistics.median(знач) if len(знач) >= 15 else None


def оценить(события, подпись, сдвиг=0, только_чистые=False):
    точки = []
    for с in события:
        if только_чистые and not с["чистое"]:
            continue
        x = изменение(с["код"], с["i"], сдвиг)
        f = фон(с["i"], сдвиг)
        if x is None or f is None or abs(с["шаг"]) < 0.004:
            continue
        точки.append((с["шаг"], x - f, с))
    if len(точки) < 10:
        print(f"{подпись:<44} мало событий ({len(точки)})")
        return
    y = [p[1] for p in точки]
    X = [[p[0]] for p in точки]
    кл = [p[2]["код"] for p in точки]
    r = мнк(y, X, кл)
    b, se = r["beta"][0], r["se"][0]
    медиана = statistics.median(abs(p[0]) for p in точки)
    print(f"{подпись:<44} событий {len(точки):>4}  медианный шаг "
          f"{медиана*100:>5.1f}%   эластичность {b:+6.2f} ± {se:.2f}   "
          f"95% [{b-1.96*se:+.2f}; {b+1.96*se:+.2f}]")
    return r


print()
оценить(постоянные, "постоянные смены цены")
оценить(постоянные, "постоянные · только ступенчатая цена", только_чистые=True)
оценить([с for с in постоянные if с["шаг"] > 0], "постоянные · только повышения")
оценить([с for с in постоянные if abs(с["шаг"]) < 0.06],
        "постоянные · мелкие (до 6%)")
оценить([с for с in постоянные if abs(с["шаг"]) >= 0.06],
        "постоянные · крупные (6% и больше)")
оценить(временные, "акции (временное снижение)")
print()
оценить(постоянные, "ПЛАЦЕБО: то же окно, сдвинутое на 4 недели назад",
        сдвиг=-ОКНО)
json.dump({"постоянные": постоянные, "временные": временные},
          open(f"{S}/события2.json", "w"), ensure_ascii=False, default=str)
