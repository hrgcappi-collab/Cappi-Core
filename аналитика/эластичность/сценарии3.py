import sys
"""Три яруса цены: где повышать безопасно, а где мы ничего не знаем."""
import json, math, statistics, sys
import os
S = sys.argv[1] if len(sys.argv) > 1 else "/tmp/эластичность"  # куда тяга.py сложила выгрузку
d = json.load(open(f"{S}/панель2.json")); панель = d["панель"]; имена = d["имена"]
себес = {r["DishCode"]: r for r in json.load(open(f"{S}/себес.json")) if r.get("DishCode")}
МЕС = 3.5
ЯРУСЫ = [("до 150 ₴", 0, 150, -0.84, 0.59), ("150–357 ₴", 150, 357, -1.63, 0.80),
         ("дороже 357 ₴", 357, 1e9, -2.58, 0.92)]
данные = {имя: [] for имя, *_ in ЯРУСЫ}
for к, недели in панель.items():
    r = себес.get(к)
    if not r or not (r.get("DishAmountInt") or 0):
        continue
    ц = statistics.median(v["мода"] for v in недели.values())
    for имя, a, b, *_ in ЯРУСЫ:
        if a <= ц < b:
            данные[имя].append(((r.get("DishDiscountSumInt") or 0) / МЕС,
                                (r.get("ProductCostBase.ProductCost") or 0) / МЕС))
            break
print(f"{'ярус':<14}{'позиций':>9}{'выручка':>12}{'фудкост':>9}{'маржа':>10}"
      f"{'безубыт. ε':>12}{'замер ε':>16}")
for имя, a, b, э, se in ЯРУСЫ:
    ряд = данные[имя]
    в = sum(x[0] for x in ряд); c = sum(x[1] for x in ряд)
    ф = c / в
    print(f"{имя:<14}{len(ряд):>9}{в/1000:>9.0f} тыс{ф*100:>8.1f}%"
          f"{(в-c)/1000:>7.0f} тыс{-1/(1-ф):>12.2f}{э:>10.2f} ±{se:.2f}")


def эффект(шаг, э, ряд):
    в = sum(x[0] for x in ряд); c = sum(x[1] for x in ряд)
    k = (1 + шаг) ** э
    return (в * (1 + шаг) - c) * k - (в - c)


print("\nЧто даст повышение по ярусам (валовая маржа, тыс ₴/мес)")
print(f"   {'шаг':<8}" + "".join(f"{имя:>26}" for имя, *_ in ЯРУСЫ))
for шаг in (0.05, 0.08, 0.10, 0.15):
    строка = f"   {шаг*100:>3.0f}%   "
    for имя, a, b, э, se in ЯРУСЫ:
        центр = эффект(шаг, э, данные[имя])
        пес = эффект(шаг, э - 1.96 * se, данные[имя])
        опт = эффект(шаг, э + 1.96 * se, данные[имя])
        строка += f"{центр/1000:>+8.0f} ({пес/1000:>+6.0f}…{опт/1000:>+6.0f})"
    print(строка)
print("\nв скобках — тот же расчёт по краям 95%-го интервала эластичности")
