# ------------------------------------------------------------- транспорт
def ключ():
    return cappi.cfg().get("OPENAI_API_KEY", "")


def доступен():
    return bool(ключ())


def _записать(бот, зачем, модель, вход, выход, из_кэша=0):
    """Каждый вызов — строкой в журнал. Считаем сами: ключ проекта счёт
    организации не видит, а нам всё равно нужен разрез по ботам."""
    try:
        строка = {"когда": datetime.now().isoformat(timespec="seconds"),
                  "бот": бот, "зачем": зачем, "модель": модель,
                  "вход": вход, "выход": выход, "кэш": из_кэша,
                  "доллары": round(цена(модель, вход, выход, из_кэша), 6)}
        with _замок:
            os.makedirs(os.path.dirname(ЖУРНАЛ), exist_ok=True)
            with open(ЖУРНАЛ, "a") as f:
                f.write(json.dumps(строка, ensure_ascii=False) + "\n")
    except Exception:
        pass          # учёт, роняющий то, что он учитывает, — плохой учёт


def _спросить(сообщения, бот, зачем, предел=300, json_ответ=False, модель=None):
    м = модель or МОДЕЛИ.get(бот) or МОДЕЛЬ
    тело = {"model": м, "messages": сообщения, "max_completion_tokens": предел}
    if json_ответ:
        тело["response_format"] = {"type": "json_object"}
    запрос = urllib.request.Request(
        АДРЕС, json.dumps(тело).encode(),
        {"Authorization": f"Bearer {ключ()}", "Content-Type": "application/json"})
    with urllib.request.urlopen(запрос, timeout=ЖДЁМ) as r:
        ответ = json.loads(r.read())
    u = ответ.get("usage") or {}
    _записать(бот, зачем, м, u.get("prompt_tokens", 0),
              u.get("completion_tokens", 0),
              (u.get("prompt_tokens_details") or {}).get("cached_tokens", 0))
    return (ответ["choices"][0]["message"].get("content") or "").strip()


# -------------------------------------------------------- ступень 1: понять
ПОНЯТЬ = (
    "Ты разбираешь запросы телеграм-бота ресторанной сети. Реши, какой экран "
    "человек хочет открыть. Ответь только JSON "
    '{"экран": "...", "аргумент": "...", "уверенность": 0.0}. '
    '«экран» — строго одно из списка ниже, слово в слово, или "" если ничего '
    "не подходит. «аргумент» — уточнение из запроса: дата, название позиции, "
    "филиал; иначе пустая строка. Ничего не считай и не придумывай."
)


def понять(текст, экраны, контекст=(), бот="core"):
    """Чего человек хотел. Разбор или None.

    `экраны` — словарь «подпись → что делает». Ответ сверяется с ключами:
    чего в списке нет, того не будет и в ответе. Описания обязательны —
    на голых подписях «сколько стоит филадельфия» уходило в
    «Себестоимость блюда», хотя спрашивали цену для гостя.
    """
    if not текст or not экраны or not доступен():
        return None
    if not isinstance(экраны, dict):
        экраны = {э: "" for э in экраны}
    # Порядок отсортирован нарочно: кэш OpenAI держится на неизменной
    # приставке запроса, а словарь в разных запусках может отдать ключи
    # в разном порядке — и кэш промахнётся на ровном месте.
    список = "\n".join(f"- {э} — {о}" if о else f"- {э}"
                       for э, о in sorted(экраны.items()))
    лента = ("\n\nПредыдущие сообщения этого человека, для контекста:\n"
             + "\n".join(f"  {с}" for с in контекст[-6:])) if контекст else ""
    try:
        сырое = _спросить(
            [{"role": "system", "content": f"{ПОНЯТЬ}\n\nЭкраны:\n{список}"},
             {"role": "user", "content": f"Запрос: {текст}{лента}"}],
            бот, "разбор", предел=120, json_ответ=True)
        о = json.loads(сырое[сырое.find("{"):сырое.rfind("}") + 1])
    except Exception:
        return None
    экран = str(о.get("экран") or "").strip()
    if экран not in экраны:
        return None
    try:
        уверенность = float(о.get("уверенность") or 0)
    except (TypeError, ValueError):
        уверенность = 0.0
    return {"экран": экран, "аргумент": str(о.get("аргумент") or "").strip(),
            "уверенность": max(0.0, min(1.0, уверенность))}


def в_кандидаты(текст, разбор, бот="core"):
    """Разобранный запрос — в список кандидатов на правило.

    Автоматически правила не появляются: сгенерированное правило может
    увести не туда, а речь про цены. Здесь копится материал, человек
    смотрит его в админке и решает.
    """
    try:
        строка = {"когда": datetime.now().isoformat(timespec="seconds"),
                  "бот": бот, "запрос": текст[:300],
                  "экран": разбор["экран"], "аргумент": разбор["аргумент"],
                  "уверенность": разбор["уверенность"]}
        with _замок:
            os.makedirs(os.path.dirname(КАНДИДАТЫ), exist_ok=True)
            with open(КАНДИДАТЫ, "a") as f:
                f.write(json.dumps(строка, ensure_ascii=False) + "\n")
    except Exception:
        pass


# ------------------------------------------------------- ступень 2: сказать
def _цифры(текст):
    сжатое = текст.replace(" ", "").replace(" ", "")
    return sorted(re.findall(r"\d+(?:[.,]\d+)?", сжатое))


def сказать(текст, кто="core"):
    """Та же мысль голосом нужного бота. Не вышло — отдаём как было.

    Числа не доверяем: если в переписанном появилось число, которого не
    было, переписанное выбрасываем целиком. Проверка слабая — она ловит
    подмену цифры и не ловит выдуманную причину, — поэтому вторую ступень
    зовут только там, где нечего выдумывать: короткие служебные фразы без
    фактов. Отчёты через неё не проходят никогда.
    """
    характер = ХАРАКТЕРЫ.get(кто)
    if not характер or not текст.strip() or not доступен():
        return текст
    try:
        новое = _спросить(
            [{"role": "system", "content": характер["кто"] +
              "\n\nПерепиши сообщение бота своим голосом. Смысл, факты и все "
              "числа сохрани в точности. Ничего не добавляй от себя — "
              "особенно причин и объяснений, которых в исходном нет. "
              "Ответь только текстом сообщения."},
             {"role": "user", "content": текст}],
            кто, "голос", предел=400)
    except Exception:
        return текст
    if not новое or len(новое) > len(текст) * 2 + 200:
        return текст
    if _цифры(новое) != _цифры(текст):
        return текст
    return новое


# --------------------------------------------------- ступень 1б: ответить
# Не всякий вопрос — про экран. «Ты кто?», «ты тут?», «а что ты умеешь» —
# это разговор, и отвечать на него «Не понял» глупо: человек обращается к
# ассистенту, а получает отказ от автомата.
#
# Цифр здесь не бывает никогда. Если вопрос про данные — ассистент не
# отвечает по памяти, а называет экран, где эти данные считаются кодом.
ОТВЕТИТЬ = (
    "Отвечай коротко, одной-двумя фразами, по-русски.\n"
    "ЗАПРЕЩЕНО называть любые числа, суммы, проценты и даты — ты их не "
    "знаешь. Если спрашивают про данные (выручка, заказы, смена, цены, "
    "скорость), не отвечай по существу, а назови экран из списка, где это "
    "считается, — например: «Это в разделе Показатели, кнопка Сейчас».\n"
    "Если вопрос не про работу вообще — ответь по-человечески и коротко."
)


def ответить(текст, экраны=None, контекст=(), бот="core"):
    """Короткий ответ словами, когда подходящего экрана нет.

    Цифры от модели не принимаются ни в каком виде: ответ с цифрой
    выбрасывается целиком. Проверка грубая и намеренно такая — отличить
    выдуманную выручку от настоящей мы здесь не можем, значит нельзя
    пропускать ни ту ни другую.
    """
    if not текст or not доступен():
        return None
    характер = ХАРАКТЕРЫ.get(бот) or ХАРАКТЕРЫ["core"]
    список = ""
    if экраны:
        список = "\n\nЭкраны бота:\n" + "\n".join(
            f"- {э} — {о}" if о else f"- {э}" for э, о in sorted(экраны.items()))
    лента = ("\n\nПредыдущие сообщения:\n" + "\n".join(f"  {с}" for с in контекст[-6:])
             if контекст else "")
    try:
        ответ = _спросить(
            [{"role": "system", "content": характер["кто"] + "\n\n" + ОТВЕТИТЬ + список},
             {"role": "user", "content": текст + лента}],
            бот, "ответ", предел=200)
    except Exception:
        return None
    ответ = (ответ or "").strip()
    if not ответ or len(ответ) > 600:
        return None
    if any(c.isdigit() for c in ответ):
        return None
    return ответ


# ------------------------------------------------------------------- голос
# Голосовое сообщение — та же команда, только надиктованная. Расшифровка
# стоит копейки и снимает главное неудобство: за рулём и на кухне печатать
# нечем, а сказать можно.
РАСШИФРОВКА = "https://api.openai.com/v1/audio/transcriptions"
МОДЕЛЬ_ГОЛОСА = "gpt-4o-mini-transcribe"
ЦЕНА_МИНУТЫ = 0.003        # доллары; у аудио тариф за время, не за токены


# Telegram называет голосовые «file_5.oga», а OpenAI расширение .oga не
# принимает — то же самое аудио под именем .ogg расшифровывается. Имя
# здесь ничего не значит для содержимого, поэтому просто говорим правду о
# контейнере: ogg он и есть.
РАСШИРЕНИЯ = {".oga": ".ogg", ".opus": ".ogg"}


def расшифровать(данные, имя="audio.ogg", бот="core", секунд=0):
    """Голос → текст. Пусто, если не вышло — но с записью в журнал.

    Раньше исключение здесь глушилось молча, и «Не разобрал голосовое»
    приходило без единого следа о причине. Искать её пришлось руками.
    """
    if not данные or not доступен():
        return ""
    корень, точка, хвост = имя.rpartition(".")
    if точка:
        имя = корень + РАСШИРЕНИЯ.get("." + хвост.lower(), "." + хвост.lower())
    граница = "----cappi" + str(len(данные))
    куски = []
    for поле, значение in (("model", МОДЕЛЬ_ГОЛОСА), ("language", "ru"),
                           ("response_format", "text")):
        куски.append(f"--{граница}\r\nContent-Disposition: form-data; "
                     f'name="{поле}"\r\n\r\n{значение}\r\n'.encode())
    куски.append(f'--{граница}\r\nContent-Disposition: form-data; name="file"; '
                 f'filename="{имя}"\r\nContent-Type: application/octet-stream'
                 f"\r\n\r\n".encode())
    куски.append(данные)
    куски.append(f"\r\n--{граница}--\r\n".encode())
    тело = b"".join(куски)
    запрос = urllib.request.Request(
        РАСШИФРОВКА, тело,
        {"Authorization": f"Bearer {ключ()}",
         "Content-Type": f"multipart/form-data; boundary={граница}"})
    try:
        with urllib.request.urlopen(запрос, timeout=60) as r:
            текст = r.read().decode("utf-8", "replace").strip()
    except urllib.error.HTTPError as e:
        подробности = e.read().decode("utf-8", "replace")[:200]
        _пожаловаться(f"расшифровка отказала: HTTP {e.code} · {имя} · {подробности}")
        return ""
    except Exception as e:
        _пожаловаться(f"расшифровка не прошла: {type(e).__name__}: {str(e)[:120]}")
        return ""
    # Аудио тарифицируется временем, а не токенами — пишем в тот же журнал
    # отдельной строкой, чтобы расходы сходились.
    try:
        строка = {"когда": datetime.now().isoformat(timespec="seconds"),
                  "бот": бот, "зачем": "голос", "модель": МОДЕЛЬ_ГОЛОСА,
                  "вход": 0, "выход": 0, "кэш": 0, "секунд": секунд,
                  "доллары": round(секунд / 60 * ЦЕНА_МИНУТЫ, 6)}
        with _замок:
            os.makedirs(os.path.dirname(ЖУРНАЛ), exist_ok=True)
            with open(ЖУРНАЛ, "a") as f:
                f.write(json.dumps(строка, ensure_ascii=False) + "\n")
    except Exception:
        pass
    return текст.strip().strip('"')


# ----------------------------------------------------------------- расходы
def расходы(дней=30):
    """Сколько потратили на ИИ: токены и доллары, в разрезе ботов."""
    порог = (datetime.now() - timedelta(days=дней)).isoformat(timespec="seconds")
    итог = {"вход": 0, "выход": 0, "кэш": 0, "доллары": 0.0, "вызовов": 0,
            "боты": {}, "модели": {}, "без_цены": set()}
    try:
        with open(ЖУРНАЛ) as f:
            строки = f.readlines()
    except FileNotFoundError:
        строки = []
    for s in строки:
        try:
            з = json.loads(s)
        except Exception:
            continue
        if з.get("когда", "") < порог:
            continue
        итог["вызовов"] += 1
        for k in ("вход", "выход"):
            итог[k] += з.get(k, 0)
        итог["доллары"] += з.get("доллары", 0.0)
        итог["кэш"] = итог.get("кэш", 0) + з.get("кэш", 0)
        for разрез, ключ_ in (("боты", "бот"), ("модели", "модель")):
            имя = з.get(ключ_) or "—"
            я = итог[разрез].setdefault(имя, {"вход": 0, "выход": 0,
                                              "доллары": 0.0, "вызовов": 0})
            я["вызовов"] += 1
            я["вход"] += з.get("вход", 0)
            я["выход"] += з.get("выход", 0)
            я["доллары"] += з.get("доллары", 0.0)
        if not цена_известна(з.get("модель")):
            итог["без_цены"].add(з.get("модель"))
    итог["без_цены"] = sorted(x for x in итог["без_цены"] if x)
    return итог
