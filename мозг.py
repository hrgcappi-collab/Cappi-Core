#!/usr/bin/env python3
"""Языковая модель для двух ботов: один мозг, две ступени.

Ставится она не в середину, а на обочину. **Команда есть — работает
скрипт, команды нет — подключается модель.** Поэтому её отсутствие
ничего не ломает: ноутбук закрыт, сеть легла, модель не ответила за пару
секунд — бот отвечает ровно то, что отвечал вчера.

Две ступени, потому что работы разные.

    Ступень 1 — ПОНЯТЬ. «Чего человек хочет» — смысл один, кем бы ни был
    спрашивающий. Общая для Core и Джамшута. Отвечает не текстом, а
    выбором из готового списка экранов: выдумать экран, которого нет,
    она физически не может, потому что ответ проверяется по списку.

    Ступень 2 — СКАЗАТЬ. Одно и то же по-разному: Core говорит с
    операционным директором, Джамшут — со сменой. Здесь и живёт разница
    характеров, и только здесь.

Железное правило, на котором всё держится: **модель понимает вопрос,
считает всегда код.** Ни одна цифра в ответе не приходит от неё. Второй
ступени запрещено даже переписывать числа: то, что она вернула с новой
цифрой, отбрасывается целиком — проверяется сравнением, а не доверием.
"""
import json
