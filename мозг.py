# ------------------------------------------------------------- транспорт
def _спросить(сообщения, ждём, предел=200, формат=None):
    тело = {"model": МОДЕЛЬ, "stream": False, "messages": сообщения,
            "options": {"temperature": 0, "num_predict": предел}}
    if формат:
        тело["format"] = формат
    запрос = urllib.request.Request(
        f"{АДРЕС}/api/chat", json.dumps(тело).encode(),
        {"Content-Type": "application/json"})
    with urllib.request.urlopen(запрос, timeout=ждём) as r:
        ответ = json.loads(r.read())
    return (ответ.get("message") or {}).get("content") or ""


def доступен():
    """Модель под рукой? Проверяем быстро и молча.

    Отдельной короткой проверкой, а не по факту неудачи: ждать двенадцать
    секунд, чтобы узнать, что ноутбук закрыт, — плохой способ.
    """
    try:
        with urllib.request.urlopen(f"{АДРЕС}/api/version",
                                    timeout=ЖДЁМ_ПИНГ) as r:
            return bool(json.loads(r.read()).get("version"))
    except Exception:
        return False


# -------------------------------------------------------- ступень 1: понять
ПОНЯТЬ = (
    "Ты — разборщик запросов телеграм-бота ресторанной сети. Твоя работа: "
    "решить, какой экран человек хочет открыть. Отвечай ТОЛЬКО объектом "
    "JSON вида {\"экран\": \"...\", \"аргумент\": \"...\", \"уверенность\": 0.0}.\n"
    "«экран» — строго одно из значений списка ниже, слово в слово. "
    "Если подходящего нет или запрос непонятен — верни \"экран\": \"\".\n"
    "«аргумент» — уточнение из запроса, если оно есть: дата, название "
    "позиции, филиал. Иначе пустая строка.\n"
    "«уверенность» — от 0 до 1.\n"
    "Ничего не придумывай и ничего не считай: числа в ответе запрещены."
)


def понять(текст, экраны, контекст=()):
    """Чего человек хотел. Возвращает разбор или None.

    `экраны` — словарь «подпись → что делает». Ответ сверяется с ключами:
    чего в списке нет, того не будет и в ответе.

    Описания обязательны, и это не украшение. На голых подписях модель
    отправляла «сколько стоит филадельфия» в «Себестоимость блюда» —
    человек спрашивал цену для гостя, а не закупочную.
    """
    if not текст or not экраны:
        return None
    if not isinstance(экраны, dict):
        экраны = {э: "" for э in экраны}
    список = "\n".join(f"- {э} — {о}" if о else f"- {э}"
                       for э, о in экраны.items())
    лента = ""
    if контекст:
        лента = ("\nПредыдущие сообщения этого человека (для контекста, "
                 "отвечать на них не надо):\n"
                 + "\n".join(f"  {с}" for с in контекст[-6:]))
    try:
        сырое = _спросить(
            [{"role": "system", "content": f"{ПОНЯТЬ}\n\nСписок экранов:\n{список}"},
             {"role": "user", "content": f"Запрос: {текст}{лента}"}],
            ЖДЁМ_ПОНЯТЬ, предел=120, формат="json")
    except Exception:
        return None
    try:
        о = json.loads(сырое[сырое.find("{"):сырое.rfind("}") + 1])
    except Exception:
        return None
    экран = str(о.get("экран") or "").strip()
    if экран not in экраны:
        # Придумала несуществующий экран — считаем, что не поняла.
        # Сверка по списку и есть вся защита: спорить с текстом бесполезно.
        return None
    try:
        уверенность = float(о.get("уверенность") or 0)
    except (TypeError, ValueError):
        уверенность = 0.0
    return {"экран": экран, "аргумент": str(о.get("аргумент") or "").strip(),
            "уверенность": max(0.0, min(1.0, уверенность))}


# ------------------------------------------------------- ступень 2: сказать
ЧИСЛА = re.compile(r"\d")


def _цифры(текст):
    """Все числа текста, как они записаны, без пробелов внутри."""
    сжатое = текст.replace(" ", "").replace(" ", "")
    return sorted(re.findall(r"\d+(?:[.,]\d+)?", сжатое))


def сказать(текст, кто="core", ждём=ЖДЁМ_СКАЗАТЬ):
    """Та же мысль голосом нужного бота. Не вышло — отдаём как было.

    Числа не доверяем никогда: если в переписанном появилось число,
    которого не было в исходном, — переписанное выбрасываем целиком.
    Модель, которая «улучшила» сумму выручки, хуже модели, которой нет.
    """
    характер = ХАРАКТЕРЫ.get(кто)
    if not характер or not текст.strip():
        return текст
    try:
        новое = _спросить(
            [{"role": "system", "content":
              характер["кто"] + "\n\nПерепиши сообщение бота своим голосом. "
              "Смысл, факты и все числа сохрани в точности. Ничего не "
              "добавляй от себя. Ответь только текстом сообщения."},
             {"role": "user", "content": текст}],
            ждём, предел=400).strip()
    except Exception:
        return текст
    if not новое or len(новое) > len(текст) * 2 + 200:
        return текст
    if _цифры(новое) != _цифры(текст):
        # Числа разъехались — значит переписала не только слова.
        return текст
    return новое
