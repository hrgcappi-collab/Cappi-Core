#!/usr/bin/env python3
"""Языковая модель для двух ботов: один мозг, две ступени.

Ставится не в середину, а на обочину. **Команда есть — работает скрипт,
команды нет — подключается модель.** Поэтому её отсутствие ничего не
ломает: кончились деньги, лёг интернет, не ответила за пару секунд — бот
отвечает ровно то, что отвечал вчера.

Две ступени, потому что работы разные.

    Ступень 1 — ПОНЯТЬ. «Чего человек хочет» — смысл один, кем бы ни был
    спрашивающий. Общая для Core и Джамшута. Отвечает не текстом, а
    выбором из готового списка экранов: выдумать экран, которого нет, она
    не может — ответ сверяется со списком.

    Ступень 2 — СКАЗАТЬ. Одно и то же по-разному: Core говорит с
    операционным директором, Джамшут — со сменой. Здесь и живёт разница
    характеров, и только здесь.

Железное правило: **модель понимает вопрос, считает всегда код.** Ни одна
цифра в ответе не приходит от неё.

Каждый разобранный запрос уходит в кандидаты на правило. Смысл всей
затеи в том, чтобы модель работала учителем, а не подпоркой: сегодня она
разобрала фразу, завтра эту фразу разбирает скрипт бесплатно, и звать
модель больше незачем.
"""
import json
import os
import re
import threading
import urllib.error
import urllib.request
from datetime import datetime, timedelta

import cappi

АДРЕС = "https://api.openai.com/v1/chat/completions"

# У каждого бота своя модель. Core разбирает вопросы операционного
# директора — там цена ошибки выше цены запроса. Джамшут отвечает смене,
# запросов больше, и luna при той же точности в девять раз дешевле.
МОДЕЛИ = {"core": "gpt-5.6-terra", "джамшут": "gpt-5.6-luna"}
МОДЕЛЬ = os.environ.get("МОЗГ_МОДЕЛЬ") or МОДЕЛИ["core"]

# Ждём мало: человек стоит над экраном, и «не понял» через две секунды
# лучше, чем верный ответ через минуту.
ЖДЁМ = 12
ПОРОГ_УВЕРЕННОСТИ = 0.6

ЖУРНАЛ = os.path.expanduser("~/.cappi/ии.jsonl")
КАНДИДАТЫ = os.path.expanduser("~/.cappi/правила.jsonl")
_замок = threading.Lock()

# Цены за миллион токенов, доллары. Таблицу держим здесь, потому что API
# цен не отдаёт, а ключ проекта не видит счёт организации. Модели, цены
# которой нет, считаются в ноль — и экран расходов прямо об этом пишет,
# вместо того чтобы тихо показывать неправду.
# (вход, кэшированный вход, выход) — доллары за миллион токенов.
# Кэш реальный: каталог экранов уходит неизменным, и 99% входа попадает в
# него, если запросы идут подряд. В жизни они идут редко, кэш остывает, и
# считать надо по факту — API говорит, сколько токенов пришло из кэша.
ЦЕНЫ = {
    "gpt-5.6-terra": (2.00, 0.20, 12.00),
    "gpt-5.6-luna":  (0.20, 0.02, 1.20),
    "gpt-5.6-sol":   (4.00, 0.40, 20.00),
    "gpt-5.4-mini":  (0.75, 0.075, 4.50),
    "gpt-5.4-nano":  (0.20, 0.02, 1.25),
    "gpt-4.1":       (2.00, 0.50, 8.00),
    "gpt-4.1-mini":  (0.40, 0.10, 1.60),
    "gpt-4.1-nano":  (0.10, 0.025, 0.40),
}


def _пожаловаться(что):
    """Сбой модели — в общий журнал сбоев, а не в тишину."""
    try:
        import bugs
        bugs.записать("апи", что[:300], где="языковая модель")
    except Exception:
        pass


def цена(модель, вход, выход, из_кэша=0):
    ставки = ЦЕНЫ.get(модель)
    if not ставки:
        return 0.0
    вх, кэш, вых = ставки
    свежий = max(вход - из_кэша, 0)
    return свежий / 1e6 * вх + из_кэша / 1e6 * кэш + выход / 1e6 * вых


def цена_известна(модель):
    return модель in ЦЕНЫ


