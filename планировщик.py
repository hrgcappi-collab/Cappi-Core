#!/usr/bin/env python3
"""Месячная цифра → план по филиалам, неделям и дням.

Человек задаёт две суммы на месяц — операционную и админскую, — а раскладка
считается. Раскладывать руками тридцать один день на два филиала и два плана
значит каждый месяц заново ошибаться в одних и тех же местах.

Откуда берутся пропорции:

- **доли филиалов** — из факта за восемь недель. Прошлогодние не годятся:
  за год Левітана прибавила пять пунктов, и раскладка по старым долям дала
  бы Лазаревой план, которого она не делает;
- **коэффициенты дня недели** — из того же факта, но **отдельно по каждому
  филиалу**: у Лазаревой пик в пятницу, у Левітани в субботу, и среда у них
  расходится на десять процентов. Один набор коэффициентов на сеть смазал бы
  обе кривые;
- **сезонный шаг** между месяцами — из прошлого года, но он уже сидит в самой
  месячной цифре, которую задаёт человек, и второй раз не применяется.

Неделя отдельно не задаётся — она сумма своих дней. Пока недельный план жил
своей жизнью, он расходился с суммой дней на 35 тысяч, и было непонятно,
какое из двух чисел настоящее.
"""
import calendar
import datetime as dt

import cappi
import report

НЕДЕЛЬ_ИСТОРИИ = 8
# В plan.json филиалы зовутся так — эти ключи читает код отчёта, не человек.
КЛЮЧ = {"Лазарева": "Зал Лазарева", "Левітана": "Зал Левитана"}
ВИДЫ = (("опер", "weekly", "month_weeks"),
        ("админ", "weekly_admin", "month_weeks_admin"))


def _дни_месяца(год, месяц):
    сколько = calendar.monthrange(год, месяц)[1]
    return [dt.date(год, месяц, d) for d in range(1, сколько + 1)]


def пропорции(по=None, недель=НЕДЕЛЬ_ИСТОРИИ):
    """Доли филиалов и коэффициенты дня недели из живого факта.

    Считаем по дням, а не по периоду целиком: коэффициент дня недели иначе
    неоткуда взять. Дней немного — восемь недель, это 56 запросов, и они
    идут параллельно.
    """
    from concurrent.futures import ThreadPoolExecutor
    по = по or (dt.date.today() - dt.timedelta(days=1))
    с = по - dt.timedelta(days=недель * 7 - 1)
    дни = [с + dt.timedelta(days=i) for i in range((по - с).days + 1)]

    def день(d):
        with cappi.Syrve() as s:
            return d, report.выручка_пиу(s, d, d)["точки"]

    with ThreadPoolExecutor(max_workers=6) as пул:
        данные = dict(пул.map(день, дни))

    сумма = {}
    по_дням = {}
    for d, точки in данные.items():
        for ф, v in точки.items():
            сумма[ф] = сумма.get(ф, 0) + v
            по_дням.setdefault(ф, {}).setdefault(d.weekday(), []).append(v)
    всего = sum(сумма.values())
    if not всего:
        raise cappi.ВнешнийСбой("Syrve", "за восемь недель нет выручки")
    доли = {ф: v / всего for ф, v in сумма.items()}
    коэф = {}
    for ф, дни_ф in по_дням.items():
        средний = сумма[ф] / len(дни)
        коэф[ф] = {wd: (sum(з) / len(з) / средний if з and средний else 1.0)
                   for wd, з in дни_ф.items()}
        for wd in range(7):
            коэф[ф].setdefault(wd, 1.0)
    return {"доли": доли, "коэф": коэф, "с": с, "по": по, "выручка": всего}


def разложить(год, месяц, суммы, проп=None):
    """{вид: сумма на месяц} → {вид: {филиал: {дата: сумма}}}.

    Остаток от округления отдаём последнему дню: месяц обязан сходиться сам
    с собой до гривны, иначе человек видит 4 350 001 там, где задал
    4 350 000, и перестаёт верить остальному.
    """
    проп = проп or пропорции()
    доли, коэф = проп["доли"], проп["коэф"]
    даты = _дни_месяца(год, месяц)
    филиалы = sorted(доли)
    норма = {ф: sum(коэф[ф][d.weekday()] for d in даты) for ф in филиалы}

    план = {}
    for вид, месячно in суммы.items():
        план[вид] = {}
        for ф in филиалы:
            цель = round(месячно * доли[ф])
            дни = [round(месячно * доли[ф] * коэф[ф][d.weekday()] / норма[ф]) for d in даты]
            дни[-1] += цель - sum(дни)
            план[вид][ф] = dict(zip(даты, дни))
        # Доли округлялись порознь — выравниваем месяц целиком по первому филиалу.
        расхождение = месячно - sum(sum(план[вид][ф].values()) for ф in филиалы)
        план[вид][филиалы[0]][даты[-1]] += расхождение
    return план


def недели(год, месяц, план):
    """Недельные суммы — как их режет отчёт: пн–вс, обрезанные краями месяца."""
    даты = _дни_месяца(год, месяц)
    out = {}
    for вид, по_филиалам in план.items():
        нед, начало, n = {}, даты[0], 1
        for d in даты:
            if d.weekday() == 6 or d == даты[-1]:
                нед[str(n)] = sum(по_филиалам[ф][x] for ф in по_филиалам
                                  for x in даты if начало <= x <= d)
                n += 1
                начало = d + dt.timedelta(days=1)
        out[вид] = нед
    return out


def записать(год, месяц, план):
    """Кладём раскладку в plan.json. Чужие месяцы не трогаем.

    Дописываем, а не заменяем: в файле лежат прошлые месяцы, и затирать их
    значит потерять историю, по которой считают выполнение.
    """
    p = report.load_plan()
    нед = недели(год, месяц, план)
    метка = f"{год}-{месяц:02d}"
    for вид, дневной, месячный in ВИДЫ:
        if вид not in план:
            continue
        разд = p.setdefault(дневной, {})
        for ф, дни in план[вид].items():
            куда = разд.setdefault(КЛЮЧ.get(ф, ф), {})
            for d, v in дни.items():
                куда[d.isoformat()] = v
        p.setdefault(месячный, {})[метка] = нед[вид]
    report.save_plan(p)
    return нед


ПОТОЛОК_РОСТА = 1.15        # насколько неделя может подрасти после недобора


def пересчёт(сегодня, вид="админ"):
    """Сколько должна сделать текущая неделя, чтобы месяц остался достижим.

    Правило заказчика: недобор прошлых недель добирается, но **разумно**.
    Поэтому отставание раскидывается на все оставшиеся недели месяца, а не
    сваливается на ближайшую, и рост недели ограничен потолком. Планка,
    в которую никто не верит, работает хуже, чем честное «отстаём».

    И ниже первоначальной неделя не опускается никогда: перевыполнили —
    значит перевыполнили, план от этого не смягчается.
    """
    недели_мес = report.недели_месяца(сегодня)
    все = report._раздел(report.load_plan(), вид, report.МЕСЯЦ).get(
        сегодня.strftime("%Y-%m")) or {}
    if not все:
        return {"нет_плана": True}

    текущая = next(((n, нач, кон) for n, нач, кон in недели_мес if нач <= сегодня <= кон), None)
    if not текущая:
        return {"нет_плана": True}
    n_тек = текущая[0]

    прошлые = [(n, нач, кон) for n, нач, кон in недели_мес if кон < сегодня]
    будущие = [(n, нач, кон) for n, нач, кон in недели_мес if нач >= сегодня]
    исходный = float(все.get(str(n_тек)) or все.get(n_тек) or 0)

    план_прошлых = sum(float(все.get(str(n)) or 0) for n, _, _ in прошлые)
    факт_прошлых = 0.0
    if прошлые:
        with cappi.Syrve() as s:
            факт_прошлых = report.выручка_пиу(s, прошлые[0][1], прошлые[-1][2])["всего"]
    недобор = max(план_прошлых - факт_прошлых, 0.0)

    # Делим пропорционально размеру недель: в короткую последнюю неделю
    # месяца класть столько же, сколько в полную, значит выдумать планку.
    остаток = [(n_тек, исходный)] + [(n, float(все.get(str(n)) or 0)) for n, _, _ in будущие]
    вес = sum(v for _, v in остаток) or 1.0
    добавка = недобор * исходный / вес

    новый = исходный + добавка
    потолок = исходный * ПОТОЛОК_РОСТА
    урезано = новый > потолок
    новый = min(новый, потолок)
    новый = max(новый, исходный)

    return {"неделя": n_тек, "с": текущая[1], "по": текущая[2],
            "исходный": исходный, "новый": round(новый),
            "недобор": недобор, "добавка": round(новый - исходный),
            "урезано": урезано, "потолок": round(потолок),
            "план_прошлых": план_прошлых, "факт_прошлых": факт_прошлых,
            "недель_впереди": len(остаток)}


def применить_пересчёт(сегодня, новый, вид="админ"):
    """Кладём пересчитанную неделю в план: и в недельный, и в дневной.

    Дни двигаем пропорционально — иначе недельная сумма и сумма дней
    разойдутся, а это уже было и стоило спора о том, какое число настоящее.
    """
    p = report.load_plan()
    метка = сегодня.strftime("%Y-%m")
    дневной, месячный = {"опер": ("weekly", "month_weeks"),
                         "админ": ("weekly_admin", "month_weeks_admin")}[вид]
    недели_мес = report.недели_месяца(сегодня)
    текущая = next(((n, нач, кон) for n, нач, кон in недели_мес if нач <= сегодня <= кон), None)
    if not текущая:
        return None
    n, нач, кон = текущая
    было = float((p.get(месячный, {}).get(метка) or {}).get(str(n)) or 0)
    if not было:
        return None
    k = новый / было
    p.setdefault(месячный, {}).setdefault(метка, {})[str(n)] = round(новый)
    разд = p.setdefault(дневной, {})
    опер = p.get("weekly", {})
    d = нач
    while d <= кон:
        for ф in set(разд) | set(опер):
            дни = разд.setdefault(ф, {})
            текущ = дни.get(d.isoformat())
            if текущ is None:
                текущ = (опер.get(ф) or {}).get(d.isoformat())
            if текущ:
                дни[d.isoformat()] = round(текущ * k)
        d += dt.timedelta(days=1)
    report.save_plan(p)
    return {"неделя": n, "было": round(было), "стало": round(новый), "коэффициент": k}


def сводка(год, месяц, план, проп=None):
    """Человекочитаемая раскладка — для карточки подтверждения."""
    нед = недели(год, месяц, план)
    даты = _дни_месяца(год, месяц)
    границы, начало, n = [], даты[0], 1
    for d in даты:
        if d.weekday() == 6 or d == даты[-1]:
            границы.append((str(n), начало, d))
            n += 1
            начало = d + dt.timedelta(days=1)
    return {"недели": нед, "границы": границы,
            "по_филиалам": {вид: {ф: sum(дни.values()) for ф, дни in по_ф.items()}
                            for вид, по_ф in план.items()},
            "итого": {вид: sum(sum(дни.values()) for дни in по_ф.values())
                      for вид, по_ф in план.items()},
            "пропорции": проп}
