#!/usr/bin/env python3
"""Кто и что может делать в боте.

Раньше доступ был один на всех: попал в TELEGRAM_ALLOWED_IDS — можешь
менять реальные цены в кассах. Для человека, которому нужно только
смотреть выручку, это лишнее право, а лишние права рано или поздно
срабатывают.

Роли, по возрастанию:

    финансист  только онлайн-оплаты mono: день, месяц, Excel — и больше
               ничего, ни выручки, ни людей (см. bot._только_оплаты)
    смотрящий  показатели, жалобы, зоны, цены на сайте — только чтение
    оператор   то же плюс смена цен
    админ      то же плюс управление доступом и служебные экраны

Список живёт в ~/.cappi/access.json и правится из бота. При первом запуске
он собирается из TELEGRAM_ALLOWED_IDS — те, кто был там, становятся
админами: иначе после обновления в боте не осталось бы никого, кто может
раздать права.
"""
import json
import os
import re
from datetime import datetime

import cappi

FILE = os.path.expanduser("~/.cappi/access.json")

РОЛИ = ["финансист", "смотрящий", "оператор", "админ"]

# Что доступно каждой роли. Ключи — то, чем пользуется бот при проверке.
ПРАВА = {
    # «ввод» — внесение цифр, от которых зависят выплаты: тайный гость,
    # правки часов. Смотрящий заявлен как «только чтение», и им он должен
    # быть на деле: до 13.09 он мог записать «5 из 4» и поднять премию.
    # «оплаты» — сверка онлайн-оплат mono. Единственное право финансиста:
    # ему нужны деньги по эквайрингу, а не выручка, смена и цены.
    "финансист": {"оплаты"},
    "смотрящий": {"показатели", "площадки", "оплаты"},
    "оператор": {"показатели", "площадки", "цены", "зоны", "ввод", "оплаты"},
    "админ": {"показатели", "площадки", "цены", "зоны", "ввод", "админка", "доступ",
              "оплаты"},
}

# Роли, которым открыто только перечисленное — всё остальное бот им
# не показывает и не выполняет, что бы ни написали.
ТОЛЬКО = {"финансист": "оплаты"}

ОПИСАНИЕ = {
    "финансист": "только онлайн-оплаты: день, месяц, Excel",
    "смотрящий": "показатели, жалобы, зоны, цены на сайте и в Glovo",
    "оператор": "всё это плюс смена цен, зоны и внесение цифр",
    "админ": "всё плюс управление доступом",
}


def _load():
    try:
        with open(FILE) as f:
            return json.load(f)
    except Exception:
        return {}


def _save(d):
    with open(FILE, "w") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    os.chmod(FILE, 0o600)


def bootstrap():
    """Первый запуск: переносим старый список в роли, всем админа.

    Без этого обновление отняло бы права у всех разом, включая того, кто
    единственный мог бы их вернуть.
    """
    d = _load()
    if d:
        return d
    ids = re.findall(r"\d+", cappi.cfg().get("TELEGRAM_ALLOWED_IDS", ""))
    d = {i: {"роль": "админ", "кто_добавил": "перенос из конфига",
             "когда": datetime.now().isoformat(timespec="seconds")} for i in ids}
    if d:
        _save(d)
    return d


def все():
    return bootstrap()


def роль(uid):
    return (все().get(str(uid)) or {}).get("роль")


def можно(uid, что):
    return что in ПРАВА.get(роль(uid) or "", set())


def есть_доступ(uid):
    return роль(uid) is not None


def добавить(uid, роль_="смотрящий", кто=None, имя=None):
    """Добавляет или переписывает роль.

    Переписывание шло мимо защиты последнего админа: `/access <id> смотрящий`
    разжаловал единственного админа, хотя кнопка «сменить роль» это запрещает.
    Дыра была ровно в том месте, где ей быть нельзя.
    """
    if роль_ not in РОЛИ:
        raise ValueError(f"неизвестная роль: {роль_}")
    d = все()
    если_был = (d.get(str(uid)) or {}).get("роль")
    if если_был == "админ" and роль_ != "админ" and _админов(d) < 2:
        raise ValueError("это последний админ — сначала назначь другого")
    d[str(uid)] = {"роль": роль_, "имя": имя, "кто_добавил": str(кто),
                   "когда": datetime.now().isoformat(timespec="seconds")}
    _save(d)


def сменить_роль(uid, роль_):
    if роль_ not in РОЛИ:
        raise ValueError(f"неизвестная роль: {роль_}")
    d = все()
    if str(uid) not in d:
        raise KeyError(uid)
    if роль(uid) == "админ" and роль_ != "админ" and _админов(d) < 2:
        raise ValueError("это последний админ — сначала назначь другого")
    d[str(uid)]["роль"] = роль_
    _save(d)


def убрать(uid):
    d = все()
    if str(uid) not in d:
        raise KeyError(uid)
    if роль(uid) == "админ" and _админов(d) < 2:
        raise ValueError("это последний админ — бот останется без управления")
    d.pop(str(uid))
    _save(d)


def _админов(d):
    return sum(1 for v in d.values() if v.get("роль") == "админ")


def подписчики_отчёта():
    """Кому слать итоги дня — всем, у кого есть доступ к показателям."""
    return с_правом("показатели")


def с_правом(что):
    """Все, у кого есть это право, — получатели тревоги про него."""
    return [int(uid) for uid, v in все().items()
            if что in ПРАВА.get(v.get("роль", ""), set())]


def только(uid):
    """Право, которым ограничена роль, или None, если роль не ограничена."""
    return ТОЛЬКО.get(роль(uid) or "")
