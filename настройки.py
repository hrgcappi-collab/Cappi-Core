#!/usr/bin/env python3
"""Настройки на человека: что показывать и что присылать.

Всем шла одна и та же сводка и одни и те же тревоги, включая тех, кому
половина не нужна: маркетологу — процент кухни, шефу — расхождения цен
на Glovo. Здесь каждый выбирает своё. Хранится в ~/.cappi/настройки.json,
по чату; чего нет — берётся по умолчанию, то есть «всё».
"""
import json
import os
import threading

ФАЙЛ = os.path.expanduser("~/.cappi/настройки.json")
_замок = threading.Lock()

# Блоки итогов дня — в том порядке, в каком они идут в сводке.
БЛОКИ = [
    ("выручка", "Выручка и план"),
    ("заказы", "Заказы, отмены, удаления"),
    ("акции", "Акции"),
    ("смена", "Смена"),
    ("время", "Время доставки"),
    ("жалобы", "Жалобы и зоны"),
]

# Тревоги, которые бот шлёт сам.
ТРЕВОГИ = [
    ("итоги", "Итоги дня в 22:30"),
    ("цены", "Цены на сайте и в Glovo разошлись"),
    ("стоп", "Позиции ушли в стоп"),
    ("списания", "Списания и правки явок"),
    ("непогода", "Непогода: компенсацию берут не со всех"),
    ("зоны", "Закрытие зон"),
]

ТОЧКИ = ["обе", "Лазарева", "Левітана"]

ПО_УМОЛЧАНИЮ = {
    "точка": "обе",
    "блоки": [к for к, _ in БЛОКИ],
    "тревоги": [к for к, _ in ТРЕВОГИ],
}


def _все():
    try:
        return json.load(open(ФАЙЛ))
    except Exception:
        return {}


def мои(chat):
    """Настройки чата, дополненные умолчаниями."""
    свои = _все().get(str(chat)) or {}
    return {**ПО_УМОЛЧАНИЮ, **свои}


def сохранить(chat, **что):
    with _замок:
        d = _все()
        d[str(chat)] = {**(d.get(str(chat)) or {}), **что}
        tmp = ФАЙЛ + ".tmp"
        with open(tmp, "w") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, ФАЙЛ)


def переключить(chat, поле, ключ):
    """Включить или выключить блок/тревогу. Возвращает новое состояние."""
    н = мои(chat)
    список = list(н[поле])
    if ключ in список:
        список.remove(ключ)
    else:
        список.append(ключ)
    сохранить(chat, **{поле: список})
    return ключ in список


def хочет(chat, тревога):
    return тревога in мои(chat)["тревоги"]


def получатели(тревога, кандидаты):
    """Кому из кандидатов слать эту тревогу."""
    return [c for c in кандидаты if хочет(c, тревога)]
