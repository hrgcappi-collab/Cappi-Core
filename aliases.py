#!/usr/bin/env python3
"""Выгрузка меню и словарь названий: как ещё могут написать позицию.

Запуск:
    python3 aliases.py            выгрузить меню и пересобрать словарь
    python3 aliases.py покажи мочі   посмотреть варианты одной позиции

Зачем. Меню украинское, ищут вперемешку и как придётся: «Мочі» пишут
«мочи» и «моти» (обе транслитерации японского もち), «Суші» — «суши» и
«суси», «сік» ищут как «сок». Приблизительный поиск часть этого ловит, но
вслепую: он не знает, что «моти» и «мочі» — одно и то же, он лишь видит
похожие буквы. Явный словарь надёжнее и, главное, правится руками.

Файлы рядом со скриптом:
    menu.json      выгрузка меню как есть — посмотреть, что вообще есть
    aliases.json   код → список написаний; генерируется, но правится руками

Ручные правки не теряются: при пересборке всё, чего нет в генерации,
сохраняется. Так что вписать «филик» для Філадельфії можно один раз.
"""
import json
import os
import sys

import cappi

HERE = os.path.dirname(os.path.abspath(__file__))
MENU_FILE = os.path.join(HERE, "menu.json")
ALIAS_FILE = os.path.join(HERE, "aliases.json")

# norm_full уже сводит украинские буквы к русским (і→и, є→е, ї→и, ґ→г),
# так что нормализованное название — это уже «общее» написание. Здесь только
# то, что остаётся: японские слоги, у которых в ходу две системы записи.
# Применяем по одной замене к нормализованному виду, без наложений — иначе
# получается комбинаторный мусор вроде «кклльашїкк».
SWAPS = [
    ("ши", "си"),      # суши / суси — Хепбёрн против Поливанова
    ("чи", "ти"),      # мочи / моти
    ("дж", "дз"),      # дзен-роллы пишут и так, и так
]

# Целые слова: перевод, который заменой букв не получить.
WORDS = {
    "сик": ["сок"], "напий": ["напиток"], "курка": ["курица"],
    "курячий": ["куриный"], "сир": ["сыр"], "вершковий": ["сливочный"],
    "вершкова": ["сливочная"], "яловичина": ["говядина"], "тунець": ["тунец"],
    "вугор": ["угорь", "унаги"], "овочи": ["овощи"], "гриби": ["грибы"],
    "гострий": ["острый"], "копчений": ["копченый"],
    "запечени": ["запеченые"], "кава": ["кофе"], "морозиво": ["мороженое"],
    "картопля": ["картофель"], "яйце": ["яйцо"], "хлиб": ["хлеб"],
    "локшина": ["лапша"], "полуниця": ["клубника"], "яблуко": ["яблоко"],
    "огирок": ["огурец"], "перець": ["перец"], "фисташка": ["фисташка"],
    "лосось": ["семга", "сьомга"], "куркою": ["курицей"],
    "креветкою": ["креветкой"], "лососем": ["лососем", "семгой"],
    "тунцем": ["тунцом"], "класик": ["классик"],
}


def variants(word):
    """Другие написания слова: японские слоги плюс перевод целых слов."""
    out = {word}
    for a, b in SWAPS:                      # по одной замене, без наложений
        if a in word:
            out.add(word.replace(a, b))
        if b in word:
            out.add(word.replace(b, a))
    out.update(WORDS.get(word, []))
    return out


def build(menu):
    """Код позиции → отсортированный список написаний."""
    out = {}
    for code, p in menu.items():
        whole = cappi.norm_full(p["name"])
        alts = {whole}
        for w in whole.split():
            if len(w) >= 3:
                alts |= variants(w)
        # Название целиком с японской заменой — «моти малина» ищут именно так.
        for a, b in SWAPS:
            if a in whole:
                alts.add(whole.replace(a, b))
        out[code] = sorted(a for a in alts if a)
    return out


def load_manual():
    """Что было вписано руками — всё, чего генератор не даёт сам."""
    try:
        return json.load(open(ALIAS_FILE))
    except Exception:
        return {}


def main():
    if len(sys.argv) > 2 and sys.argv[1] in ("покажи", "show"):
        data = load_manual()
        menu = json.load(open(MENU_FILE))
        q = cappi.norm_full(" ".join(sys.argv[2:]))
        for code, p in menu.items():
            if q in cappi.norm_full(p["name"]):
                print(f"\n{code}  {p['name']}  {p['price']} ₴")
                print("   ", ", ".join(data.get(code, [])))
        return

    print("Читаю меню из Syrve…")
    menu = {code: {"name": p["name"], "price": p["price"], "id": p["id"],
                   "in_menu": p["in_menu"]}
            for code, p in cappi.cloud_prices().items()}
    json.dump(menu, open(MENU_FILE, "w"), ensure_ascii=False, indent=1)
    print(f"  меню выгружено: {len(menu)} позиций → menu.json")

    было = load_manual()
    стало = build(menu)
    # Ручные добавления сохраняем: всё, чего нет в свежей генерации.
    ручных = 0
    for code, alts in было.items():
        new = set(стало.get(code, []))
        extra = [a for a in alts if a not in new]
        if extra:
            стало[code] = sorted(new | set(extra))
            ручных += len(extra)
    json.dump(стало, open(ALIAS_FILE, "w"), ensure_ascii=False, indent=1)
    total = sum(len(v) for v in стало.values())
    print(f"  словарь собран: {total} написаний на {len(стало)} позиций"
          + (f", из них {ручных} вписаны руками" if ручных else ""))
    print(f"\nПравится руками: {ALIAS_FILE}")
    print("Добавленное там переживёт следующую пересборку.")


if __name__ == "__main__":
    main()
