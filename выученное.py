#!/usr/bin/env python3
"""Что бот однажды разобрал с помощью модели — и больше не будет.

Схема заказчика: сначала скрипт, не понял — модель, разобрала — записали,
и в следующий раз отвечает опять скрипт. Модель работает учителем, а не
подпоркой: каждый разобранный запрос удешевляет следующий до нуля.

Хранится файлом, а не кодом. Сгенерированный код пришлось бы выкатывать,
а главное — его нельзя было бы отменить без правки репозитория. Словарь
читается на лету, правится и чистится из админки.

Ищем в два захода. Сначала точное совпадение по нормализованной фразе:
«Скок отмен?» и «скок отмен» — одно и то же. Потом по набору слов: у
записи копятся синонимы, то есть все формулировки, которые к ней уже
приводили, и совпадения по большинству слов достаточно.
"""
import json
import os
import threading
from datetime import datetime

ФАЙЛ = os.path.expanduser("~/.cappi/выученное.json")
_замок = threading.Lock()
_память = {"когда": 0.0, "данные": None}

# Сколько слов запроса должно совпасть с записью, чтобы считать её той же.
ДОЛЯ_СЛОВ = 0.6
МИН_СЛОВ = 2
МИН_ОСНОВА = 4          # общее начало короче — совпадает со всем подряд


def _слова(текст):
    низ = "".join(c if c.isalnum() else " " for c in (текст or "").lower())
    return {с for с in низ.split() if len(с) > 2}


def _родня(а, б):
    """Одно ли это слово: «отмен» и «отмены», «смене» и «смена».

    Сравниваем общее начало, а не равенство: русские окончания иначе
    разводят одну и ту же мысль по разным записям, и выученное не
    срабатывает ровно там, где человек переформулировал.
    """
    общее = 0
    for x, y in zip(а, б):
        if x != y:
            break
        общее += 1
    return общее >= МИН_ОСНОВА


def _пересечение(а, б):
    return sum(1 for x in а if any(_родня(x, y) for y in б))


def ключ(текст):
    """Нормализованная фраза: регистр и знаки не считаются."""
    return " ".join(sorted(_слова(текст)))


def _читать():
    """Файл читаем не чаще раза в пять секунд: лезть на диск на каждое
    сообщение незачем, а изменения из админки должны подхватываться сами."""
    import time
    if _память["данные"] is not None and time.time() - _память["когда"] < 5:
        return _память["данные"]
    try:
        d = json.load(open(ФАЙЛ))
    except Exception:
        d = {}
    _память["данные"], _память["когда"] = d, time.time()
    return d


def _писать(d):
    tmp = ФАЙЛ + ".tmp"
    os.makedirs(os.path.dirname(ФАЙЛ), exist_ok=True)
    with open(tmp, "w") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, ФАЙЛ)
    _память["данные"] = d
    _память["когда"] = __import__("time").time()


def найти(текст):
    """Знаем ли мы эту фразу. Возвращает запись или None."""
    d = _читать()
    к = ключ(текст)
    if к in d:
        return d[к]
    слова = _слова(текст)
    if len(слова) < МИН_СЛОВ:
        return None
    # Совпадение по большинству слов: формулировки у людей разные, а
    # смысл один. Требуем совпадения в обе стороны, иначе короткий запрос
    # цепляется к длинной записи, где его слова — лишь часть.
    лучшее, вес = None, 0.0
    for запись in d.values():
        свои = set(запись.get("слова") or [])
        if not свои:
            continue
        общее = _пересечение(слова, свои)
        доля = общее / max(len(слова), len(свои))
        if доля >= ДОЛЯ_СЛОВ and доля > вес:
            лучшее, вес = запись, доля
    return лучшее


def запомнить(текст, экран, аргумент="", бот="core", уверенность=0.0):
    """Записать разобранное. Повтор той же фразы копит синонимы."""
    with _замок:
        d = _читать()
        к = ключ(текст)
        запись = d.get(к)
        if запись and запись.get("экран") != экран:
            # Та же фраза — другой экран. Модель передумала; доверять
            # такому нельзя, и запись выбрасываем: пусть лучше спросит
            # заново, чем уверенно ведёт не туда.
            d.pop(к, None)
            _писать(d)
            return None
        if запись:
            запись["раз"] = запись.get("раз", 1) + 1
            запись["слова"] = sorted(set(запись.get("слова") or []) | _слова(текст))
            фразы = запись.setdefault("фразы", [])
            if текст not in фразы and len(фразы) < 10:
                фразы.append(текст[:120])
        else:
            запись = {"экран": экран, "аргумент": аргумент, "бот": бот,
                      "слова": sorted(_слова(текст)), "фразы": [текст[:120]],
                      "раз": 1, "уверенность": round(уверенность, 2),
                      "когда": datetime.now().isoformat(timespec="seconds")}
        d[к] = запись
        _писать(d)
        return запись


def забыть(к):
    with _замок:
        d = _читать()
        убрали = d.pop(к, None)
        if убрали:
            _писать(d)
        return убрали


def всё():
    """Выученное списком, свежее сверху."""
    d = _читать()
    строки = [dict(з, ключ=к) for к, з in d.items()]
    return sorted(строки, key=lambda з: (-з.get("раз", 0), з.get("когда", "")))


def сводка():
    строки = всё()
    return {"фраз": len(строки),
            "срабатываний": sum(з.get("раз", 1) - 1 for з in строки),
            "экранов": len({з["экран"] for з in строки})}
