#!/usr/bin/env python3
"""Заливка факта в таблицу заказчика — через Apps Script, а не через Google API.

Почему так. У проекта нет зависимостей, только стандартная библиотека, и это
держится нарочно. Сервисный аккаунт Google требует подписи RS256, а RSA в
стандартной библиотеке нет — пришлось бы тянуть google-auth в образ и следить
за ним. Скрипт, живущий внутри самой книги, не требует ничего: обычный POST,
как в Джамшута.

Пишем **по ключу, а не по номеру строки**. Человек вставит строку сверху —
и запись по номеру начнёт молча портить соседние дни. Ключ (дата в первом
столбце) переживает любую перестановку, а чего не нашли, про то скрипт
честно отвечает списком.

Трогаем только столбцы факта. Формулы процентов и итогов — их, не наши:
переписать формулу значением легко, вернуть обратно некому.
"""
import datetime as dt
import json
import urllib.error
import urllib.request

import cappi
import report

# Столбцы листа «План-факт». Порядок задан шаблоном; если заказчик переставит
# столбцы, меняется только это место.
ФАКТ_ЛАЗАРЕВА = 7
ФАКТ_ЛЕВИТАНА = 8
ФАКТ_СЕТЬ = 9
ПРОЦЕНТ_ОПЕР = 10
ПРОЦЕНТ_АДМИН = 11

# Блок недель устроен иначе, чем блок дней, и это не опечатка шаблона:
# у недели нет разбивки по филиалам, поэтому столбцов на три меньше и факт
# начинается раньше.
#
#   дни     A дата · B день · C–F планы · G Лаз · H Лев · I сеть · J % · K %
#   недели  A неделя · B период · C дней · D план опер · E план админ ·
#           F факт · G % опер · H % админ
#
# До 11.10.2026 недельные строки слались с дневной картой столбцов. Ключ
# «1 нед» при этом находился, скрипт отвечал «записано», список ненайденных
# был пуст — и выручка Лазаревой десять дней ложилась в столбец «% опер».
# Столбец «Факт» не получал ничего, поэтому «Итог» внизу стоял нулём.
ФАКТ_НЕДЕЛИ = 6
ПРОЦЕНТ_ОПЕР_НЕДЕЛИ = 7
ПРОЦЕНТ_АДМИН_НЕДЕЛИ = 8
# Остатки дневной карты, затёртые в недельных строках по ошибке. Чистим их
# явно: пустая строка стирает ячейку, а молча оставленный мусор выглядит
# как данные.
ЛИШНИЕ_У_НЕДЕЛИ = (ФАКТ_СЕТЬ, ПРОЦЕНТ_ОПЕР, ПРОЦЕНТ_АДМИН)

ЛИСТ_ПО_УМОЛЧАНИЮ = "План-факт"

ФИЛИАЛЫ = {"Лазарева": ФАКТ_ЛАЗАРЕВА, "Левітана": ФАКТ_ЛЕВИТАНА}

# Итог и проценты считаем сами, а не формулами в книге. Формулы не пережили
# импорт шаблона: Google выбросил их при загрузке, и столбцы «Факт сеть»,
# «% опер», «% админ» остались пустыми навсегда (01.10.2026). Число, которое
# мы написали, останется числом; формула зависит от того, как книгу однажды
# скопируют или пересохранят.


def настроена():
    c = cappi.cfg()
    return bool(c.get("PLAN_SHEET_URL") and c.get("PLAN_SHEET_TOKEN"))


def _лист():
    return cappi.cfg().get("PLAN_SHEET_LIST") or ЛИСТ_ПО_УМОЛЧАНИЮ


class _БезРедиректа(urllib.request.HTTPRedirectHandler):
    """Редирект не автоматический: за ним идём сами.

    Apps Script на POST отвечает 302 на script.googleusercontent.com, а
    urllib тащит на редирект заголовки исходного запроса — Content-Type и
    Content-Length от тела, которого в GET уже нет. Google отвечает на это
    404, и выглядит оно как «скрипт удалён», хотя скрипт жив: тот же адрес
    на GET отдаёт 200. Поэтому идём по Location вручную и чистым запросом.
    """

    def redirect_request(self, *a, **k):
        return None


_ОТКРЫВАТЕЛЬ = urllib.request.build_opener(_БезРедиректа)


def _послать(тело, timeout=120):
    """Запрос к скрипту книги. Ответ всегда JSON — даже отказ."""
    c = cappi.cfg()
    if not настроена():
        raise cappi.ВнешнийСбой("Таблица", "не заданы PLAN_SHEET_URL/TOKEN")
    тело = {"токен": c["PLAN_SHEET_TOKEN"], "лист": _лист(), **тело}
    req = urllib.request.Request(
        c["PLAN_SHEET_URL"], data=json.dumps(тело, ensure_ascii=False).encode(),
        headers={"Content-Type": "application/json", **cappi.UA})
    try:
        try:
            with _ОТКРЫВАТЕЛЬ.open(req, timeout=timeout) as r:
                сырое = r.read()
        except urllib.error.HTTPError as e:
            куда = e.headers.get("Location") if e.code in (301, 302, 303, 307) else None
            if not куда:
                raise
            with _ОТКРЫВАТЕЛЬ.open(
                    urllib.request.Request(куда, headers=dict(cappi.UA)),
                    timeout=timeout) as r:
                сырое = r.read()
    except Exception as e:
        raise cappi.ВнешнийСбой("Таблица", str(getattr(e, "reason", e))[:80]) from None
    try:
        ответ = json.loads(сырое)
    except ValueError:
        # Google отдаёт HTML, когда развёртывание закрыто или протухло.
        # Это не «сломался бот», это «таблица не пускает».
        raise cappi.ВнешнийСбой("Таблица", "ответ не JSON — проверь развёртывание") from None
    if not isinstance(ответ, dict):
        raise cappi.ВнешнийСбой("Таблица", "ответ не объект")
    if ответ.get("ошибка"):
        raise cappi.ВнешнийСбой("Таблица", str(ответ["ошибка"])[:120])
    return ответ


def проверить():
    """Жива ли связь. Для экрана «Проверка связи» и сторожа источников."""
    о = _послать({"что": "пинг"}, timeout=60)
    return {"лист": о.get("лист"), "строк": о.get("строк")}


def _ключ(день):
    """Как день подписан в первом столбце таблицы."""
    return f"{день:%d.%m}"


def _факт(дни):
    """Выручка по ПиУ по филиалам за каждый из дней.

    Спрашиваем по одному дню: в таблице строка на день, и сложить обратно
    из периода нельзя — разбивки по датам ПиУ не даёт.
    """
    out = {}
    with cappi.Syrve() as s:
        for д in дни:
            out[д] = report.выручка_пиу(s, д, д)["точки"]
    return out


def залить(дни):
    """Факт за перечисленные дни. Возвращает, сколько значений записано."""
    дни = [д for д in дни if д <= dt.date.today()]
    if not дни:
        return {"записано": 0, "дней": 0, "ненайдены": []}
    факты = _факт(дни)
    строки = []
    for д in дни:
        значения = {}
        сеть = 0.0
        for имя, столбец in ФИЛИАЛЫ.items():
            v = факты[д].get(имя)
            if v:
                значения[str(столбец)] = round(v)
                сеть += v
        if not значения:
            continue
        значения[str(ФАКТ_СЕТЬ)] = round(сеть)
        # Проценты целыми числами: заголовок столбца уже говорит «%», а
        # формат ячейки через эту ручку не задать — дробь 1,17 человек
        # прочитает как рубль семнадцать.
        for вид, столбец in (("опер", ПРОЦЕНТ_ОПЕР), ("админ", ПРОЦЕНТ_АДМИН)):
            план = report.plan_for(д, вид)[0]
            if план:
                значения[str(столбец)] = round(сеть / план * 100)
        строки.append({"ключ": _ключ(д), "значения": значения})
    if not строки:
        return {"записано": 0, "дней": 0, "ненайдены": []}
    строки += _итоги_недель({д.strftime("%Y-%m") for д in дни})
    о = _послать({"строки": строки})
    return {"записано": о.get("записано", 0), "дней": len(дни),
            "ненайдены": о.get("ненайдены") or [], "лист": о.get("лист")}


def _итоги_недель(месяцы):
    """Строки «1 нед», «2 нед» … — факт недели и проценты.

    В книге это были формулы SUM, но после импорта они застыли нулями:
    планы успели посчитаться и сохранились числами, а факт остался нулём
    навсегда. Пересчитываем сами по тем же границам недель, что и отчёт.
    """
    сегодня = dt.date.today()
    строки = []
    for метка in sorted(месяцы):
        год, мес = (int(x) for x in метка.split("-"))
        for n, нач, кон in report.недели_месяца(dt.date(год, мес, 1)):
            по = min(кон, сегодня)
            if по < нач:
                continue
            with cappi.Syrve() as s:
                точки = report.выручка_пиу(s, нач, по)["точки"]
            # У недели в книге одно число факта — по сети. Филиалы считаем
            # только затем, чтобы их сложить: разбивки в блоке нет.
            сеть = sum(точки.get(имя) or 0 for имя in ФИЛИАЛЫ)
            if not сеть:
                continue
            значения = {str(ФАКТ_НЕДЕЛИ): round(сеть)}
            for вид, столбец in (("опер", ПРОЦЕНТ_ОПЕР_НЕДЕЛИ),
                                 ("админ", ПРОЦЕНТ_АДМИН_НЕДЕЛИ)):
                план = sum(report.plan_for(нач + dt.timedelta(days=i), вид)[0] or 0
                           for i in range((по - нач).days + 1))
                if план:
                    значения[str(столбец)] = round(сеть / план * 100)
            for столбец in ЛИШНИЕ_У_НЕДЕЛИ:
                значения[str(столбец)] = ""
            строки.append({"ключ": f"{n} нед", "значения": значения})
    return строки


def залить_день(день=None):
    """Один день. Умолчание — вчера: сегодняшняя смена ещё не закрыта."""
    день = день or (dt.date.today() - dt.timedelta(days=1))
    return залить([день])


def залить_месяц(день=None):
    """Весь месяц по вчерашний день — для кнопки «перезалить»."""
    день = день or dt.date.today()
    первое = день.replace(day=1)
    последний = min(день - dt.timedelta(days=1), day_конец(первое))
    if последний < первое:
        return {"записано": 0, "дней": 0, "ненайдены": []}
    дни = [первое + dt.timedelta(days=i) for i in range((последний - первое).days + 1)]
    return залить(дни)


def day_конец(первое):
    следующий = dt.date(первое.year + первое.month // 12, первое.month % 12 + 1, 1)
    return следующий - dt.timedelta(days=1)


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "пинг":
        print(json.dumps(проверить(), ensure_ascii=False))
    elif len(sys.argv) > 1 and sys.argv[1] == "месяц":
        print(json.dumps(залить_месяц(), ensure_ascii=False))
    else:
        д = dt.date.fromisoformat(sys.argv[1]) if len(sys.argv) > 1 else None
        print(json.dumps(залить_день(д), ensure_ascii=False))
