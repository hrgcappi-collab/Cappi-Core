#!/usr/bin/env python3
"""Заливка факта в таблицу заказчика — через Apps Script, а не через Google API.

Почему так. У проекта нет зависимостей, только стандартная библиотека, и это
держится нарочно. Сервисный аккаунт Google требует подписи RS256, а RSA в
стандартной библиотеке нет — пришлось бы тянуть google-auth в образ и следить
за ним. Скрипт, живущий внутри самой книги, не требует ничего: обычный POST,
как в Джамшута.

Пишем **по ключу, а не по номеру строки**. Человек вставит строку сверху —
и запись по номеру начнёт молча портить соседние дни. Ключ (дата в первом
столбце) переживает любую перестановку, а чего не нашли, про то скрипт
честно отвечает списком.

Трогаем только столбцы факта. Формулы процентов и итогов — их, не наши:
переписать формулу значением легко, вернуть обратно некому.
"""
import datetime as dt
import json
import urllib.request

import cappi
import report

# Столбцы листа «План-факт». Порядок задан шаблоном; если заказчик переставит
# столбцы, меняется только это место.
ФАКТ_ЛАЗАРЕВА = 7
ФАКТ_ЛЕВИТАНА = 8
ЛИСТ_ПО_УМОЛЧАНИЮ = "План-факт"

ФИЛИАЛЫ = {"Лазарева": ФАКТ_ЛАЗАРЕВА, "Левітана": ФАКТ_ЛЕВИТАНА}


def настроена():
    c = cappi.cfg()
    return bool(c.get("PLAN_SHEET_URL") and c.get("PLAN_SHEET_TOKEN"))


def _лист():
    return cappi.cfg().get("PLAN_SHEET_LIST") or ЛИСТ_ПО_УМОЛЧАНИЮ


def _послать(тело, timeout=120):
    """Запрос к скрипту книги. Ответ всегда JSON — даже отказ."""
    c = cappi.cfg()
    if not настроена():
        raise cappi.ВнешнийСбой("Таблица", "не заданы PLAN_SHEET_URL/TOKEN")
    тело = {"токен": c["PLAN_SHEET_TOKEN"], "лист": _лист(), **тело}
    req = urllib.request.Request(
        c["PLAN_SHEET_URL"], data=json.dumps(тело, ensure_ascii=False).encode(),
        headers={"Content-Type": "application/json", **cappi.UA})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            сырое = r.read()
    except Exception as e:
        raise cappi.ВнешнийСбой("Таблица", str(getattr(e, "reason", e))[:80]) from None
    try:
        ответ = json.loads(сырое)
    except ValueError:
        # Google отдаёт HTML, когда развёртывание закрыто или протухло.
        # Это не «сломался бот», это «таблица не пускает».
        raise cappi.ВнешнийСбой("Таблица", "ответ не JSON — проверь развёртывание") from None
    if not isinstance(ответ, dict):
        raise cappi.ВнешнийСбой("Таблица", "ответ не объект")
    if ответ.get("ошибка"):
        raise cappi.ВнешнийСбой("Таблица", str(ответ["ошибка"])[:120])
    return ответ


def проверить():
    """Жива ли связь. Для экрана «Проверка связи» и сторожа источников."""
    о = _послать({"что": "пинг"}, timeout=60)
    return {"лист": о.get("лист"), "строк": о.get("строк")}


def _ключ(день):
    """Как день подписан в первом столбце таблицы."""
    return f"{день:%d.%m}"


def _факт(дни):
    """Выручка по ПиУ по филиалам за каждый из дней.

    Спрашиваем по одному дню: в таблице строка на день, и сложить обратно
    из периода нельзя — разбивки по датам ПиУ не даёт.
    """
    out = {}
    with cappi.Syrve() as s:
        for д in дни:
            out[д] = report.выручка_пиу(s, д, д)["точки"]
    return out


def залить(дни):
    """Факт за перечисленные дни. Возвращает, сколько значений записано."""
    дни = [д for д in дни if д <= dt.date.today()]
    if not дни:
        return {"записано": 0, "дней": 0, "ненайдены": []}
    факты = _факт(дни)
    строки = []
    for д in дни:
        значения = {}
        for имя, столбец in ФИЛИАЛЫ.items():
            v = факты[д].get(имя)
            if v:
                значения[str(столбец)] = round(v)
        if значения:
            строки.append({"ключ": _ключ(д), "значения": значения})
    if not строки:
        return {"записано": 0, "дней": 0, "ненайдены": []}
    о = _послать({"строки": строки})
    return {"записано": о.get("записано", 0), "дней": len(строки),
            "ненайдены": о.get("ненайдены") or [], "лист": о.get("лист")}


def залить_день(день=None):
    """Один день. Умолчание — вчера: сегодняшняя смена ещё не закрыта."""
    день = день or (dt.date.today() - dt.timedelta(days=1))
    return залить([день])


def залить_месяц(день=None):
    """Весь месяц по вчерашний день — для кнопки «перезалить»."""
    день = день or dt.date.today()
    первое = день.replace(day=1)
    последний = min(день - dt.timedelta(days=1), day_конец(первое))
    if последний < первое:
        return {"записано": 0, "дней": 0, "ненайдены": []}
    дни = [первое + dt.timedelta(days=i) for i in range((последний - первое).days + 1)]
    return залить(дни)


def day_конец(первое):
    следующий = dt.date(первое.year + первое.month // 12, первое.month % 12 + 1, 1)
    return следующий - dt.timedelta(days=1)


if __name__ == "__main__":
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "пинг":
        print(json.dumps(проверить(), ensure_ascii=False))
    elif len(sys.argv) > 1 and sys.argv[1] == "месяц":
        print(json.dumps(залить_месяц(), ensure_ascii=False))
    else:
        д = dt.date.fromisoformat(sys.argv[1]) if len(sys.argv) > 1 else None
        print(json.dumps(залить_день(д), ensure_ascii=False))
