#!/usr/bin/env python3
"""Себестоимость: сколько стоит то, из чего сделано блюдо.

Syrve показывает себестоимость в Office отдельной колонкой, но наружу её
не отдаёт: через API доступны только состав техкарт и складские остатки.
Проверено — ни `assemblyCharts/getPrepared`, ни `getTree` цены не
содержат. Поэтому считаем сами.

Как считается цена единицы:

    сырьё          сумма остатка / количество остатка по всем складам
    полуфабрикат   если есть остаток — по остатку, иначе раскладываем
                   его техкарту до сырья
    вода           ноль: у «Вода питьевая (только для рецептур)» нет ни
                   остатка, ни карты, и это правильно

Результат сверен с колонкой «Себестоимость, грн.» в Syrve Office на
пятнадцати заготовках: четырнадцать совпали до копейки, одна разошлась
на 0,4%. То есть метод воспроизводит их же цифру, а не даёт свою.
"""
import json
import time
from datetime import date, timedelta

import cappi

# Позиции, у которых себестоимость честно нулевая.
БЕСПЛАТНЫЕ_АРТИКУЛЫ = {"00417"}      # вода питьевая для рецептур

_КЭШ = {"когда": 0}
_КЭШ_ЖИВЁТ = 900


class НетЦены(Exception):
    def __init__(self, название):
        self.название = название
        super().__init__(название)


def _данные(обновить=False):
    """Техкарты, остатки и номенклатура — одним заходом.

    Три тяжёлых запроса, вместе около четырёх мегабайт. Держим в памяти
    четверть часа: за это время ни карты, ни остатки заметно не меняются,
    а без кэша каждый просчёт стоил бы полминуты.
    """
    if not обновить and time.time() - _КЭШ["когда"] < _КЭШ_ЖИВЁТ:
        return _КЭШ
    сегодня = date.today()
    with cappi.Syrve() as s:
        карты = json.loads(cappi._get(
            f"{s.host}/resto/api/v2/assemblyCharts/getAll?key={s.key}"
            f"&dateFrom={сегодня}&dateTo={сегодня + timedelta(days=1)}",
            timeout=60))["assemblyCharts"]
        товары = {p["id"]: p for p in s.products() if not p.get("deleted")}
        # Цена единицы — сумма остатка на количество. Но остаток на 00:00
        # бывает отрицательным (рис ушёл в −15 кг: списали больше, чем
        # оприходовали) или нулевым — и позиция «теряла» цену, хотя цена у
        # неё есть. Берём модуль, а если сегодня остатка нет вовсе —
        # смотрим вчера, позавчера и неделю назад.
        цена = {}
        for дн in (0, 1, 2, 7):
            t = (сегодня - timedelta(days=дн)).isoformat() + "T00:00:00"
            остатки = json.loads(cappi._get(
                f"{s.host}/resto/api/v2/reports/balance/stores?key={s.key}"
                f"&timestamp={t}", timeout=90))
            поток = {}
            for о in остатки:
                кол = о.get("amount") or 0
                if abs(кол) < 0.001:
                    continue
                c = поток.setdefault(о["product"], [0.0, 0.0])
                c[0] += о.get("sum") or 0
                c[1] += кол
            for k, v in поток.items():
                if k not in цена and abs(v[1]) > 0.001 and v[0] * v[1] > 0:
                    цена[k] = abs(v[0] / v[1])
            if дн == 0:
                сегодняшних = len(цена)
    _КЭШ.update({
        "когда": time.time(),
        "цена": цена,
        "карта": {a["assembledProductId"]: a for a in карты
                  if a.get("items") and a.get("dateTo") is None},
        "товары": товары,
        "по_артикулу": {str(p.get("num")): p for p in товары.values()},
    })
    return _КЭШ


def за_единицу(pid, глубина=0):
    """Цена одной единицы позиции. Бросает НетЦены, если её неоткуда взять."""
    д = _данные()
    товар = д["товары"].get(pid, {})
    if str(товар.get("num")) in БЕСПЛАТНЫЕ_АРТИКУЛЫ:
        return 0.0
    if pid in д["цена"]:
        return д["цена"][pid]
    карта = д["карта"].get(pid)
    if not карта or глубина > 6:
        raise НетЦены(товар.get("name", "неизвестная позиция"))
    выход = карта.get("assembledAmount") or 1
    итого = 0.0
    for и in карта["items"]:
        кол = (и.get("amountIn") or и.get("amount") or 0) / выход
        итого += за_единицу(и["productId"], глубина + 1) * кол
    return итого


def по_составу(строки):
    """Себестоимость по списку [(позиция, количество)].

    Позиция — словарь из номенклатуры. Возвращает разбор построчно и
    итог: без разбора цифра бесполезна, спорить с ней нельзя.
    """
    разбор, итого, дыры = [], 0.0, []
    for товар, кол in строки:
        try:
            ед = за_единицу(товар["id"])
            сумма = ед * кол
            итого += сумма
        except НетЦены as e:
            ед = сумма = None
            дыры.append(e.название)
        разбор.append({"название": товар["name"], "артикул": товар.get("num"),
                       "кол": кол, "за_единицу": ед, "сумма": сумма})
    разбор.sort(key=lambda с: -(с["сумма"] or 0))
    return {"строки": разбор, "итого": итого, "дыры": дыры}


def блюда(pid):
    """Себестоимость готового блюда по его техкарте."""
    д = _данные()
    карта = д["карта"].get(pid)
    if not карта:
        return None
    выход = карта.get("assembledAmount") or 1
    строки = []
    for и in карта["items"]:
        товар = д["товары"].get(и["productId"])
        if not товар:
            continue
        строки.append((товар, (и.get("amountIn") or и.get("amount") or 0) / выход))
    итог = по_составу(строки)
    итог["выход"] = выход
    return итог


def фудкост(себестоимость, цена):
    return себестоимость / цена * 100 if цена else None
