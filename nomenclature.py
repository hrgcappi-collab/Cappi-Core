#!/usr/bin/env python3
"""Словарь номенклатуры: найти позицию так, как её называет человек.

В Syrve 1477 позиций, и названия там складские, а не человеческие: рис
называется «Рис на суши (готовый) ПФ», лосось — «Лосось филе (акт
разбора)», вода — «Вода питьевая (только для рецептур)». Повар, шеф или
технолог напишет «рис», «лосось», «вода» — и должен получить то, что
имел в виду, а не «не нашёл».

Поэтому здесь три слоя, от точного к приблизительному:

    1. артикул                      «00087»
    2. точное имя или ядро имени    «рис на суши» = «Рис на суши (готовый) ПФ»
    3. все слова запроса в названии «рис суши»
    4. приблизительно, по буквам    «моцарела» → «Сыр моцарелла ПФ»

Ядро имени — название без служебного хвоста: «ПФ», «(акт разбора)»,
«(только для рецептур)», «(готовый)». Хвост нужен кладовщику, а тому, кто
ищет, он только мешает.

Когда кандидатов несколько, модуль их не выбирает: возвращает список, и
выбирает человек кнопкой. Молча взять первый — это списать со склада не
то, и узнать об этом на переучёте.
"""
import json
import os
import re
import time
from difflib import SequenceMatcher

import cappi

СЛОВАРЬ_ФАЙЛ = os.path.expanduser("~/.cappi/словарь.json")

# Служебные хвосты складских названий. Порядок важен: длинные раньше.
ХВОСТЫ = [
    r"\(только для рецептур\)", r"\(акт разбора\)", r"\(готовый\)",
    r"\(списание в кг\)", r"\(брутто\)", r"\(нетто\)",
    r"\bпф\b", r"\bп/ф\b", r"\bnew\b",
]

# Что человек пишет вместо складского названия. Дополняется руками:
# словарь, который нельзя поправить, рано или поздно начинают обходить.
СИНОНИМЫ = {
    "рис": "рис на суши",
    "сливочный сыр": "сыр сливочный",
    "креветка": "креветка тигровая",
    "вода": "вода питьевая",
    "мука": "мука",
    "тесто": "тесто на пиццу",
    "соус спайси": "спайси соус",
}

_КЭШ = {"когда": 0, "позиции": []}
_КЭШ_ЖИВЁТ = 1800


def всё(обновить=False):
    """Вся номенклатура: id, артикул, название, тип, единица."""
    if обновить or time.time() - _КЭШ["когда"] > _КЭШ_ЖИВЁТ:
        with cappi.Syrve() as s:
            позиции = [p for p in s.products() if not p.get("deleted")]
        _КЭШ.update({"когда": time.time(), "позиции": позиции})
    return _КЭШ["позиции"]


def ядро(название):
    """Название без служебного хвоста, нормализованное."""
    имя = cappi.norm_full(название)
    for хвост in ХВОСТЫ:
        имя = re.sub(хвост, " ", имя)
    return re.sub(r"\s+", " ", имя).strip(" ,.-")


def _синоним(запрос):
    з = cappi.norm_full(запрос)
    return cappi.norm_full(СИНОНИМЫ.get(з, з))


def ручные():
    """Привязки, сделанные людьми: «рис» → конкретный артикул."""
    try:
        return json.load(open(СЛОВАРЬ_ФАЙЛ))
    except Exception:
        return {}


def запомнить(запрос, артикул):
    """Человек выбрал из списка — в следующий раз не спрашиваем.

    Это и есть главный источник словаря: он растёт от того, как люди
    действительно пишут, а не от того, как мы это себе представляли.
    """
    d = ручные()
    d[cappi.norm_full(запрос)] = str(артикул)
    tmp = СЛОВАРЬ_ФАЙЛ + ".tmp"
    with open(tmp, "w") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, СЛОВАРЬ_ФАЙЛ)


def найти(запрос, типы=None, предел=8):
    """Кандидаты по запросу, от точных к приблизительным.

    `типы` — ограничить поиск («GOODS», «PREPARED», «DISH»). Для состава
    блюда нужны сырьё и полуфабрикаты, но не готовые блюда.
    """
    запрос = (запрос or "").strip()
    if not запрос:
        return []
    позиции = всё()
    if типы:
        позиции = [p for p in позиции if p.get("type") in типы]

    # артикул — однозначно
    if re.fullmatch(r"\d{3,6}", запрос):
        точно = [p for p in позиции if str(p.get("num")) == запрос.zfill(5)
                 or str(p.get("num")) == запрос]
        if точно:
            return [(p, 100) for p in точно]

    # ручная привязка — она главнее любых догадок
    привязан = ручные().get(cappi.norm_full(запрос))
    if привязан:
        точно = [p for p in позиции if str(p.get("num")) == привязан]
        if точно:
            return [(p, 100) for p in точно]

    з = _синоним(запрос)
    слова = з.split()
    out = []
    for p in позиции:
        полное = cappi.norm_full(p["name"])
        я = ядро(p["name"])
        if з == я or з == полное:
            вес = 95
        elif я.startswith(з) or полное.startswith(з):
            вес = 80 - min(len(я) - len(з), 20) * 0.5
        elif слова and all(с in полное for с in слова):
            вес = 65 - min(len(я) - len(з), 20) * 0.5
        else:
            похоже = SequenceMatcher(None, з, я).ratio()
            if похоже < 0.72:
                continue
            вес = похоже * 55
        # Сырьё и заготовки в составе нужнее готовых блюд.
        if p.get("type") == "PREPARED":
            вес += 3
        elif p.get("type") == "DISH":
            вес -= 6
        out.append((p, вес))
    out.sort(key=lambda x: (-x[1], len(x[0]["name"])))
    return out[:предел]


def одна(запрос, типы=None):
    """Единственный кандидат или None, если выбор неочевиден.

    Неочевиден — это когда второй кандидат почти так же хорош. Тогда
    спрашиваем человека: разница между «Лосось филе» и «Лосось жареный ПФ»
    в блюде — это разная себестоимость и разное списание.
    """
    к = найти(запрос, типы)
    if not к:
        return None
    if len(к) == 1 or к[0][1] >= 95 or к[0][1] - к[1][1] >= 15:
        return к[0][0]
    return None
