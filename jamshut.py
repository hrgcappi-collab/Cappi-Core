#!/usr/bin/env python3
"""Клиент Джамшута — бота закрытия зон доставки.

Отношения между ботами односторонние, и это осознанно.

Core знает адрес Джамшута и его токен, ходит к нему и (когда появятся
управляющие ручки) отдаёт команды. Джамшут о Core не знает ничего: у него
нет ни адреса, ни токена, ни способа что-либо здесь вызвать. Пуш-вебхук он
умеет, но только если ему дать URL и ключ, — мы не дали.

Почему так, а не «оба видят друг друга». Взаимный доступ означает, что
поломка или компрометация любого из двух открывает второго. При
односторонней связи Джамшут остаётся ровно тем, чем был: источником
событий, который можно отключить, не трогая Core.

Изоляция при этом не мешает: они на одном сервере, но в разных
контейнерах, с разными пользователями внутри и без общих файлов. Единственная
точка соприкосновения — HTTP с токеном.
"""
import json
import urllib.error
from datetime import date, datetime, timedelta

import cappi


class НетУправления(RuntimeError):
    """Ручка управления ещё не реализована на стороне Джамшута."""


def _база():
    c = cappi.cfg()
    return c.get("JAMSHUT_URL", "").rstrip("/"), c.get("JAMSHUT_TOKEN", "")


def _заголовки():
    _, токен = _база()
    return {"Authorization": f"Bearer {токен}"}


def настроен():
    адрес, токен = _база()
    return bool(адрес and токен)


def _get(path, timeout=30):
    адрес, _ = _база()
    return json.loads(cappi._get(адрес + path, _заголовки(), timeout=timeout))


def _post(path, тело, timeout=30):
    """Управляющий вызов. Пока таких ручек нет — переводим 404 в понятный
    отказ, чтобы в боте было написано «не умеет», а не «ошибка 404»."""
    адрес, _ = _база()
    try:
        return cappi._post(адрес + path, тело, _заголовки(), timeout=timeout)
    except RuntimeError as e:
        if "404" in str(e) or "405" in str(e):
            raise НетУправления(
                f"Джамшут пока не принимает {path} — нужна ручка на его стороне")
        raise


# ------------------------------------------------------------------ чтение
def здоровье():
    адрес, _ = _база()
    return json.loads(cappi._get(адрес + "/health", timeout=15))


def состояние():
    """Какие зоны закрыты прямо сейчас."""
    return _get("/zones/state")


def события(с=None, по=None, лимит=1000):
    с = с or date.today()
    по = по or с
    return _get(f"/zones/events?from={с}&to={по}&limit={лимит}", timeout=60).get("data", [])


def история(дней=7):
    """События за период кусками: у них за nginx таймаут 30 секунд."""
    out, конец = [], date.today()
    начало = конец - timedelta(days=дней - 1)
    шаг = начало
    while шаг <= конец:
        до = min(шаг + timedelta(days=6), конец)
        try:
            out += события(шаг, до, лимит=10000)
        except Exception:
            pass
        шаг = до + timedelta(days=1)
    return out


def сводка(дней=7):
    """Кто и сколько закрывал зоны — по людям и по районам."""
    закрытия = [e for e in история(дней) if e.get("event") == "zone.close"]
    по_людям, по_районам, авто = {}, {}, 0
    for e in закрытия:
        if e.get("auto") or e.get("source") == "bot":
            авто += 1
            кто = "автоматически"
        else:
            кто = e.get("actor") or "—"
        по_людям[кто] = по_людям.get(кто, 0) + 1
        район = e.get("district") or e.get("branch") or "без района"
        по_районам[район] = по_районам.get(район, 0) + 1
    минут = sum(e.get("duration_min") or 0 for e in закрытия)
    return {"закрытий": len(закрытия), "минут": минут, "авто": авто,
            "по_людям": по_людям, "по_районам": по_районам}


# --------------------------------------------------------------- управление
# Ручек ещё нет — контракт согласован ниже и передан их разработчику.
# Методы написаны заранее: когда ручки появятся, включатся сами, без правок
# в боте.

def закрыть_зону(zone_ids, минут, кто, район=None):
    return _post("/zones/close", {"zone_ids": list(zone_ids), "duration_min": минут,
                                  "actor": кто, "district": район, "source": "core"})


def открыть_зону(zone_ids, кто):
    return _post("/zones/open", {"zone_ids": list(zone_ids), "actor": кто,
                                 "source": "core"})


def справочник_зон():
    """Список зон с названиями — нужен, чтобы показывать не голые номера."""
    return _get("/zones/list")
