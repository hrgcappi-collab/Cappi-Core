#!/usr/bin/env python3
"""Хранилище сбоев: всё, что пошло не так, в одном месте.

До этого следы поломок лежали в трёх разных местах и в двух форматах:
непонятые команды в unknown.log, отказы доступа в denied.log, а падения
не сохранялись вообще — traceback уходил в stdout контейнера и жил до
перезапуска. Чтобы узнать, что у людей ломается, надо было лезть на сервер
и читать логи, поэтому этого не делал никто.

Здесь всё складывается в один журнал и группируется по отпечатку: сто
одинаковых падений — это одна проблема со счётчиком, а не сто строк. Разбор
идёт из бота: посмотреть, пометить починенным, отложить.

Формат — JSONL: дописывать в конец дёшево и безопасно, а если файл на
записи оборвётся, потеряется одна последняя строка, а не весь журнал.
"""
import hashlib
import json
import os
import threading
import traceback
from datetime import datetime, timedelta

ФАЙЛ = os.path.expanduser("~/.cappi/bugs.jsonl")
_замок = threading.Lock()

ТИПЫ = {
    "сбой": "💥 Падение",
    "апи": "🔌 Внешний сервис",
    "непонял": "🗣 Не понял запрос",
    "отказ": "🔐 Нет доступа",
    "жалоба": "🐞 Пожаловался человек",
}

СТАТУСЫ = ("новый", "в работе", "починен", "не баг")

# Сколько держим. Журнал нужен для разбора, а не для вечного хранения:
# полугодовой давности падение в коде, которого уже нет, только мешает.
ХРАНИТЬ_ДНЕЙ = 90


def _отпечаток(тип, где, что):
    """Что считать «той же самой» ошибкой.

    Берём тип, место и текст без цифр: «нет позиции 03395» и «нет позиции
    04122» — одна проблема, и разносить их по разным карточкам значит
    утопить журнал в повторах.
    """
    сырое = f"{тип}|{где}|{''.join(c for c in что if not c.isdigit())[:120]}"
    return hashlib.sha1(сырое.encode()).hexdigest()[:10]


def записать(тип, что, где="", кто=None, детали=None):
    """Одна запись в журнал. Никогда не бросает исключений сама.

    Логирование, роняющее то, что оно логирует, — худший вид помощи.
    """
    try:
        строка = {
            "когда": datetime.now().isoformat(timespec="seconds"),
            "тип": тип, "что": str(что)[:400], "где": где,
            "кто": str(кто) if кто else None,
            "детали": (детали or "")[:4000],
            "id": _отпечаток(тип, где, str(что)),
        }
        with _замок:
            os.makedirs(os.path.dirname(ФАЙЛ), exist_ok=True)
            with open(ФАЙЛ, "a") as f:
                f.write(json.dumps(строка, ensure_ascii=False) + "\n")
        return строка["id"]
    except Exception:
        return None


def сбой(где, исключение, кто=None):
    """Падение с полным traceback — без него разбор превращается в гадание."""
    return записать("сбой", f"{type(исключение).__name__}: {исключение}",
                    где=где, кто=кто, детали=traceback.format_exc())


def читать():
    try:
        with open(ФАЙЛ) as f:
            out = []
            for s in f:
                s = s.strip()
                if not s:
                    continue
                try:
                    out.append(json.loads(s))
                except json.JSONDecodeError:
                    continue      # оборванная строка — пропускаем, не падаем
            return out
    except FileNotFoundError:
        return []


# --------------------------------------------------------------- состояния
# Статусы держим отдельным файлом: журнал только дописывается, и менять в
# нём задним числом ничего нельзя — иначе это уже не журнал.
СТАТУС_ФАЙЛ = os.path.expanduser("~/.cappi/bugs_state.json")


def состояния():
    try:
        return json.load(open(СТАТУС_ФАЙЛ))
    except Exception:
        return {}


def пометить(ид, статус, кто=None):
    if статус not in СТАТУСЫ:
        raise ValueError(статус)
    d = состояния()
    d[ид] = {"статус": статус, "кто": str(кто),
             "когда": datetime.now().isoformat(timespec="seconds")}
    tmp = СТАТУС_ФАЙЛ + ".tmp"
    with open(tmp, "w") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, СТАТУС_ФАЙЛ)


def статус(ид):
    return (состояния().get(ид) or {}).get("статус", "новый")


# ------------------------------------------------------------------ разбор
def группы(дней=14, тип=None, скрывать_починенные=True):
    """Сбои, сгруппированные по отпечатку: что, сколько раз, когда последний.

    Сортировка по свежести последнего случая, а не по счётчику: сто раз
    упавшее в июне и починенное неинтересно, а вчерашнее падение — да.
    """
    порог = datetime.now() - timedelta(days=дней)
    гр = {}
    for з in читать():
        try:
            когда = datetime.fromisoformat(з["когда"])
        except Exception:
            continue
        if когда < порог or (тип and з["тип"] != тип):
            continue
        g = гр.setdefault(з["id"], {
            "id": з["id"], "тип": з["тип"], "что": з["что"], "где": з["где"],
            "раз": 0, "первый": когда, "последний": когда,
            "люди": set(), "детали": з.get("детали") or "", "примеры": []})
        g["раз"] += 1
        g["первый"] = min(g["первый"], когда)
        g["последний"] = max(g["последний"], когда)
        if з.get("кто"):
            g["люди"].add(з["кто"])
        if len(g["примеры"]) < 5:
            g["примеры"].append(з["что"])
        if з.get("детали"):
            g["детали"] = з["детали"]
    сост = состояния()
    out = []
    for g in гр.values():
        g["статус"] = (сост.get(g["id"]) or {}).get("статус", "новый")
        g["люди"] = sorted(g["люди"])
        if скрывать_починенные and g["статус"] in ("починен", "не баг"):
            # Починенное прячем, но только пока оно не повторилось после
            # пометки: вернувшийся баг должен снова быть виден.
            когда_пометили = (сост.get(g["id"]) or {}).get("когда")
            try:
                if когда_пометили and g["последний"] <= datetime.fromisoformat(
                        когда_пометили):
                    continue
            except Exception:
                continue
        out.append(g)
    return sorted(out, key=lambda g: g["последний"], reverse=True)


def сводка(дней=14):
    г = группы(дней)
    return {"проблем": len(г), "случаев": sum(x["раз"] for x in г),
            "падений": sum(x["раз"] for x in г if x["тип"] == "сбой"),
            "новых": sum(1 for x in г if x["статус"] == "новый")}


def подчистить():
    """Убираем старьё — иначе файл растёт вечно."""
    порог = datetime.now() - timedelta(days=ХРАНИТЬ_ДНЕЙ)
    живые = []
    for з in читать():
        try:
            if datetime.fromisoformat(з["когда"]) >= порог:
                живые.append(з)
        except Exception:
            pass
    tmp = ФАЙЛ + ".tmp"
    with _замок:
        with open(tmp, "w") as f:
            for з in живые:
                f.write(json.dumps(з, ensure_ascii=False) + "\n")
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, ФАЙЛ)
    return len(живые)


# ------------------------------------------------------- контекст разговора
# Человек жмёт «Ошибка» не на пустом месте, а после нескольких сообщений:
# что-то спросил, получил не то, переспросил, получил то же. Одна реплика
# без этой цепочки бесполезна — по «не работает» не чинят.
#
# Поэтому держим последние реплики чата: и свои, и человека. На диске, а не
# только в памяти: перезапуск после падения — это ровно тот момент, когда
# человек идёт жаловаться, и терять контекст именно там нельзя.
ДИАЛОГ = os.path.expanduser("~/.cappi/диалог.jsonl")
ПОМНИМ = 14              # реплик на чат
ДИАЛОГ_СТРОК = 4000      # после этого файл подрезаем
РЕПЛИКА = 600            # длиннее не храним: отчёт целиком тут не нужен

_диалоги = {}
_диалог_замок = threading.Lock()
_дописано = 0


def _подрезать_диалог():
    try:
        with open(ДИАЛОГ) as f:
            строки = f.readlines()
    except FileNotFoundError:
        return
    if len(строки) <= ДИАЛОГ_СТРОК:
        return
    tmp = ДИАЛОГ + ".tmp"
    with open(tmp, "w") as f:
        f.writelines(строки[-ДИАЛОГ_СТРОК // 2:])
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, ДИАЛОГ)


def _поднять_диалоги():
    """Читаем хвост файла в память — один раз, при запуске."""
    try:
        with open(ДИАЛОГ) as f:
            строки = f.readlines()[-ДИАЛОГ_СТРОК:]
    except FileNotFoundError:
        return
    for s in строки:
        try:
            з = json.loads(s)
            _диалоги.setdefault(з["чат"], []).append(з)
        except Exception:
            continue
    for чат in _диалоги:
        _диалоги[чат] = _диалоги[чат][-ПОМНИМ:]


def запомнить(чат, роль, текст, кто=None):
    """Одна реплика разговора. Роль — «человек» или «бот»."""
    if чат is None or not текст:
        return
    global _дописано
    з = {"когда": datetime.now().isoformat(timespec="seconds"),
         "чат": чат, "роль": роль, "кто": str(кто) if кто else None,
         "текст": str(текст)[:РЕПЛИКА]}
    try:
        with _диалог_замок:
            лента = _диалоги.setdefault(чат, [])
            лента.append(з)
            del лента[:-ПОМНИМ]
            os.makedirs(os.path.dirname(ДИАЛОГ), exist_ok=True)
            with open(ДИАЛОГ, "a") as f:
                f.write(json.dumps(з, ensure_ascii=False) + "\n")
            _дописано += 1
            if _дописано % 500 == 0:
                _подрезать_диалог()
    except Exception:
        pass          # память о разговоре не стоит того, чтобы ронять ответ


def разговор(чат, сколько=ПОМНИМ):
    with _диалог_замок:
        return list(_диалоги.get(чат, []))[-сколько:]


def недавние(кто, минут=20):
    """Что упало у этого человека за последние минуты — без гадания.

    Жалоба почти всегда идёт сразу за сбоем, и сбой уже записан вместе с
    traceback. Связать одно с другим по времени — надёжнее, чем просить
    человека пересказать ошибку.
    """
    порог = datetime.now() - timedelta(minutes=минут)
    out = []
    for з in читать():
        try:
            если_когда = datetime.fromisoformat(з["когда"])
        except Exception:
            continue
        # Свои же жалобы сюда не берём: человек и так видит, что нажал.
        if (если_когда >= порог and з.get("тип") != "жалоба"
                and (not кто or з.get("кто") == str(кто))):
            out.append(з)
    return out[-6:]


# Признаки в ответах бота, по которым видно, чем разговор кончился.
СЛЕДЫ = [
    ("Не понял", "непонял", "бот не разобрал текст"),
    ("Не знаю команду", "непонял", "неизвестная команда"),
    ("Сломалось", "сбой", "обработчик упал"),
    ("не отвечает", "апи", "внешний сервис молчал"),
    ("Нет доступа", "отказ", "не хватило прав"),
    ("может оператор или админ", "отказ", "не хватило прав"),
    ("админский экран", "отказ", "не хватило прав"),
    ("Нет позиции", "данные", "позиция не нашлась"),
    ("Не нашёл", "данные", "не нашлось в номенклатуре"),
    ("Менять нечего", "данные", "в списке нечего менять"),
    ("устарел", "поток", "карточка истекла"),
]


def разобрать(реплики):
    """Что видно из разговора без человека: тип, вывод, на что смотреть.

    Разбор нарочно грубый и честный: он не угадывает причину, а называет
    то, что прямо видно в ленте. Всё остальное — работа над журналом.
    """
    люди = [р for р in реплики if р["роль"] == "человек"]
    боты = [р for р in реплики if р["роль"] == "бот"]
    вывод, тип = [], "жалоба"

    for ответ in reversed(боты):
        совпало = next((с for с in СЛЕДЫ if с[0].lower() in ответ["текст"].lower()),
                       None)
        if совпало:
            тип = совпало[1] if совпало[1] in ТИПЫ else "жалоба"
            вывод.append(совпало[2])
            break

    # Повтор — самый честный признак, что ответ не подошёл: человек не
    # станет писать одно и то же дважды, если его поняли.
    тексты = [" ".join(р["текст"].split()).lower() for р in люди]
    for т in set(тексты):
        if тексты.count(т) > 1 and len(т) > 2:
            вывод.append(f"повторял одно и то же {тексты.count(т)} раза — "
                         f"значит, ответ не подошёл")
            break

    if люди and not боты:
        вывод.append("бот вообще не ответил")

    последнее = люди[-1]["текст"] if люди else ""
    return {"тип": тип, "вывод": вывод, "запрос": последнее,
            "реплик": len(реплики)}


def жалоба(чат, кто, реплики, разбор_=None):
    """Кладём жалобу в тот же журнал, где всё остальное — с лентой целиком."""
    р = разбор_ or разобрать(реплики)
    лента = "\n".join(
        f"{з['когда'][11:16]} {'→' if з['роль'] == 'человек' else '←'} "
        f"{' '.join(з['текст'].split())[:300]}" for з in реплики)
    что = (" ".join(р["запрос"].split())[:120] or "без текста")
    рядом = недавние(кто)
    if рядом:
        лента += "\n\nРядом в журнале:\n" + "\n".join(
            f"  {з['когда'][11:16]} {ТИПЫ.get(з['тип'], з['тип'])}: {з['что'][:90]}"
            for з in рядом)
    return записать("жалоба", что, где="кнопка «Ошибка»", кто=кто,
                    детали=("; ".join(р["вывод"]) or "человек не уточнил") +
                           "\n\n" + лента)


def дописать(ид, текст, кто=None):
    """Комментарий человека к уже заведённой жалобе — отдельной строкой.

    Журнал только дописывается, поэтому не правим старую запись, а кладём
    новую с тем же отпечатком: в карточке она встанет рядом, в примерах.
    """
    try:
        строка = {
            "когда": datetime.now().isoformat(timespec="seconds"),
            "тип": "жалоба", "что": f"описание: {str(текст)[:300]}",
            "где": "кнопка «Ошибка»", "кто": str(кто) if кто else None,
            "детали": "", "id": ид}
        with _замок:
            with open(ФАЙЛ, "a") as f:
                f.write(json.dumps(строка, ensure_ascii=False) + "\n")
        return True
    except Exception:
        return False


_поднять_диалоги()
