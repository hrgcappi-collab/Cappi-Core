#!/usr/bin/env python3
"""KPI шефа и су-шефов.

Все определения собраны здесь, в одном месте и на виду. Так задумано:
таблица, из которой это выросло, считалась руками, и формула в ней не
выдерживалась — за июнь списание брали с одного счёта, за июль с другого,
переучёт расходился на 750 гривен без объяснения. От этих цифр зависят
премии, поэтому важнее не «как было», а чтобы правило было одно и его
можно было прочитать.

Что откуда:

    выручка кухни   продажи с типом «Блюдо», сумма со скидкой, без
                    удалённых. Напитки, товары, логистический сбор и
                    модификаторы к работе кухни отношения не имеют.
    время выдачи    Cooking.KitchenTime.Avg — «продолжительность работы
                    кухни» в Syrve, тот же показатель, что в таблице.
    списание        счета 02.08 + 03.01 + 03.06 из P&L
    переучёт        счета 02.04 + 02.09 из P&L
    негатив         Loopa, tone=negative, делённый на заказы
    тайник          вносится руками: этих данных нет ни в одной системе

Проценты считаются от выручки кухни, а не от общей: су-шеф не отвечает за
продажи напитков.
"""
import json
import os
import re
from datetime import date, timedelta

import cappi
import report

ФАЙЛ = os.path.expanduser("~/.cappi/kpi.json")

# Счета P&L. Держим списком, чтобы поправить состав можно было здесь, а не
# искать по коду.
СЧЕТА_СПИСАНИЯ = ("02.08", "03.01", "03.06")
СЧЕТА_ПЕРЕУЧЁТА = ("02.04", "02.09")

# Нормативы из таблицы KPI.
НОРМА = {
    "списание": 0.2,        # % от выручки кухни
    "переучёт": 0.5,        # % отклонения, по модулю
    "негатив": 1.0,         # % негативных отзывов от заказов
    "тайник": 75.0,         # % пройденных
    "время_су": {"Лазарева": 25.0, "Левітана": 20.0},   # минут, по филиалам
    "время_шеф": 22.5,      # минут, среднее по сети
}

ТОЧКИ = {"Лазарева": "Лазарева", "Левітана": "Левітана", "Левитана": "Левітана"}

# Веса взяты из таблицы KPI. У шефа они неравные: тайник, время и негатив
# весят вдвое против переучёта и списания — так решили, и это не наше дело.
ВЕСА = {
    "су-шеф": {"списание": 1000, "время": 1000, "негатив": 1000,
               "тайник": 1000, "переучёт": 1000},
    "шеф": {"тайник": 1250, "время": 1250, "негатив": 1250,
            "переучёт": 625, "списание": 625},
}


def люди(значение=None):
    """Кто занимает роли. Хранится у нас, а не берётся из Syrve.

    Справочник Syrve отстаёт от жизни: су-шеф Левітани Ткачук Максим
    записан там поваром, а су-шеф Лазаревой — учётчиком. Это кадровые
    данные, и править их из бота неправильно; проще держать соответствие
    у себя и обновлять командой, когда люди меняются.
    """
    try:
        d = json.load(open(ФАЙЛ))
    except Exception:
        d = {}
    if значение is None:
        return d.get("люди", {})
    d["люди"] = значение
    json.dump(d, open(ФАЙЛ, "w"), ensure_ascii=False, indent=1)
    return значение


def кто(s, роль):
    """ФИО. Сначала своё соответствие, потом поиск в Syrve.

    Ищем в HQ, а не в ТП: кадровые правки делают там, а до ТП-базы они
    доезжают обменом по расписанию. Из-за этого су-шеф Левітани полдня
    числился поваром — роль ему уже поменяли, а мы смотрели в базу, куда
    изменение ещё не пришло.

    Роль проверяем и основную, и дополнительные: у су-шефа Лазаревой
    основная — «Учетчик», а «Су-шеф» стоит второй.
    """
    своё = люди().get(роль)
    if своё:
        return своё
    import xml.etree.ElementTree as ET
    c = cappi.cfg()
    try:
        with cappi.Syrve(c["SYRVE_SERVER_URL"], c["SYRVE_API_LOGIN"],
                         c["SYRVE_API_PASSWORD"]) as hq:
            emp = ET.fromstring(cappi._get(
                f"{hq.host}/resto/api/employees?key={hq.key}", timeout=90))
            roles = ET.fromstring(cappi._get(
                f"{hq.host}/resto/api/employees/roles?key={hq.key}", timeout=60))
    except Exception:
        return None
    имена = {x.findtext("id"): x.findtext("name") for x in roles.iter("role")}
    искомое = "шеф-повар" if роль == "шеф" else "су-шеф"
    for e in emp.iter("employee"):
        if e.findtext("deleted") == "true":
            continue
        имя = e.findtext("name") or ""
        свои = [имена.get(e.findtext("mainRoleId") or "") or ""]
        свои += [имена.get(i) or "" for i in (e.findtext("rolesIds") or "").split(",")]
        должности = " ".join(свои).lower()
        подходит = искомое in должности or искомое in имя.lower()
        if роль != "шеф":
            # «Левітана» и «Левитана» — одно место, разные буквы. В карточке
            # Syrve пишут по-русски, у нас в отчётах по-украински, и без
            # приведения алфавитов су-шеф просто не находится.
            подходит = подходит and cappi.norm_full(роль)[:6] in cappi.norm_full(имя)
        if подходит:
            # «Загодиренко София (су-шеф, Лазарева)» — скобки лишние.
            return имя.split("(")[0].strip()
    return None


def _месяц(day):
    первое = date(day.year, day.month, 1)
    следующее = date(day.year + day.month // 12, day.month % 12 + 1, 1)
    return первое, следующее


# ------------------------------------------------------------------ из Syrve
def _olap(s, тип, поля, агрегаты, с, по, фильтры=None):
    поле_даты = "OpenDate.Typed" if тип == "SALES" else "DateTime.DateTyped"
    body = {"reportType": тип, "buildSummary": False,
            "groupByRowFields": поля, "aggregateFields": агрегаты,
            "filters": {поле_даты: {"filterType": "DateRange",
                                    "periodType": "CUSTOM",
                                    "from": с.isoformat(), "to": по.isoformat()},
                        **(фильтры or {})}}
    return cappi._post(f"{s.host}/resto/api/v2/reports/olap?key={s.key}",
                       body, timeout=240).get("data", [])


def кухня(s, day):
    """Выручка кухни и время выдачи по филиалам.

    Двумя запросами, и это не лень. Выручка кухни — только блюда: напитки
    и товары к работе кухни отношения не имеют. А время выдачи считается
    по заказу целиком, и если отобрать в нём одни блюда, среднее уедет:
    на июле выходило 32,5 минуты вместо 31,8.
    """
    с, по = _месяц(day)
    out = {}
    for x in _olap(s, "SALES", ["Conception"], ["DishDiscountSumInt", "UniqOrderId"],
                   с, по, {"DishType": {"filterType": "IncludeValues", "values": ["DISH"]},
                           **report.НЕ_УДАЛЁННЫЕ}):
        имя = ТОЧКИ.get((x.get("Conception") or "").lstrip("012 ").strip())
        if имя:
            out[имя] = {"выручка": x.get("DishDiscountSumInt", 0) or 0,
                        "заказов": x.get("UniqOrderId", 0) or 0}
    for x in _olap(s, "SALES", ["Conception"], ["Cooking.KitchenTime.Avg"],
                   с, по, report.НЕ_УДАЛЁННЫЕ):
        имя = ТОЧКИ.get((x.get("Conception") or "").lstrip("012 ").strip())
        if имя in out:
            сек = x.get("Cooking.KitchenTime.Avg") or 0
            out[имя]["время"] = сек / 60 if сек > 200 else сек
    return out


def счета(s, day):
    """Суммы по счетам P&L за месяц, по филиалам.

    Разрез по концепции: «1 Лазарева» и «2 Левітана». Су-шеф отвечает за
    свою кухню, и общая цифра по сети для его премии бесполезна.

    Возвращает {'Лазарева': {'02.04': 12789, …}, …, 'ВСЕГО': {…}}.
    """
    с, по = _месяц(day)
    out = {"ВСЕГО": {}}
    for x in _olap(s, "TRANSACTIONS", ["Conception", "Account.Name"],
                   ["Sum.ResignedSum"], с, по):
        m = re.match(r"^(\d\d\.\d\d)", (x.get("Account.Name") or "").strip())
        if not m:
            continue
        счёт, сумма = m.group(1), (x.get("Sum.ResignedSum") or 0)
        точка = ТОЧКИ.get((x.get("Conception") or "").lstrip("012 ").strip())
        if точка:
            out.setdefault(точка, {})
            out[точка][счёт] = out[точка].get(счёт, 0) + сумма
        out["ВСЕГО"][счёт] = out["ВСЕГО"].get(счёт, 0) + сумма
    return out


def негатив_по_качеству(day):
    """Негативные отзывы про еду.

    В критерии сказано «щодо якості страв», а не «все жалобы»: за курьера
    и упаковку кухня не отвечает. Категории в Loopa бывают составными —
    «kitchen, packing» — поэтому считаем все, где кухня упомянута, а не
    только чистый kitchen. За июль это 55 против 42 и 104.
    """
    д1, д2 = _месяц(day)
    r = report._loopa(**{"from": д1.isoformat(),
                         "to": (д2 - timedelta(days=1)).isoformat(),
                         "tone": "negative", "group_by": "category"})
    return sum(g["count"] for g in (r or {}).get("groups", [])
               if "kitchen" in (g.get("key") or ""))


# ------------------------------------------------------------ вносится руками
def тайники(месяц=None, значение=None):
    """Результаты тайного гостя. Читаются и пишутся только руками —
    в системах их нет."""
    try:
        d = json.load(open(ФАЙЛ))
    except Exception:
        d = {}
    ключ = (месяц or date.today()).strftime("%Y-%m")
    if значение is None:
        return d.get(ключ)
    d[ключ] = значение
    json.dump(d, open(ФАЙЛ, "w"), ensure_ascii=False, indent=1)
    return значение


def выплата(r, роль):
    """Сколько причитается по каждому критерию и всего.

    Считаем по принципу «выполнил — получил», без частичных начислений.
    В исходной таблице они встречались: 0,09% списания давали 500 из 1000,
    а время 28,3 при норме 22,5 — «закрыл на 50%». Правила для этого нигде
    не записано, а угадывать в вопросе премий нельзя: пусть лучше цифра
    будет строгой и понятной, чем правдоподобной и произвольной.
    """
    н, веса = НОРМА, ВЕСА["шеф" if роль == "шеф" else "су-шеф"]
    т = r.get("тайники") or {}
    строки = []

    def добавить(имя, факт, норма, ок, единица="%"):
        сумма = веса[имя] if ок else 0
        строки.append({"критерий": имя, "факт": факт, "норма": норма,
                       "выполнен": ок, "сумма": сумма, "единица": единица})

    if роль == "шеф":
        всего = sum(v.get("всего", 0) for v in т.values())
        пройдено = sum(v.get("пройдено", 0) for v in т.values())
        проц = пройдено / всего * 100 if всего else None
        добавить("тайник", проц, н["тайник"], проц is not None and проц >= н["тайник"])
        добавить("время", r["время_среднее"], н["время_шеф"],
                 r["время_среднее"] <= н["время_шеф"], "мин")
        добавить("негатив", r["негатив_%"], н["негатив"], r["негатив_%"] <= н["негатив"])
        добавить("переучёт", r["переучёт_%"], н["переучёт"],
                 abs(r["переучёт_%"]) <= н["переучёт"])
        добавить("списание", r["списание_%"], н["списание"],
                 r["списание_%"] <= н["списание"])
    else:
        v = r["точки"].get(роль) or {}
        норма_вр = v.get("норма_времени") or н["время_шеф"]
        мои = т.get(роль) or {}
        проц = (мои["пройдено"] / мои["всего"] * 100) if мои.get("всего") else None
        добавить("списание", v.get("списание_%", 0), н["списание"],
                 v.get("списание_%", 0) <= н["списание"])
        добавить("время", v.get("время", 0), норма_вр,
                 v.get("время", 0) <= норма_вр, "мин")
        добавить("негатив", r["негатив_%"], н["негатив"], r["негатив_%"] <= н["негатив"])
        добавить("тайник", проц, н["тайник"], проц is not None and проц >= н["тайник"])
        добавить("переучёт", v.get("переучёт_%", 0), н["переучёт"],
                 abs(v.get("переучёт_%", 0)) <= н["переучёт"])
    return {"строки": строки, "итого": sum(x["сумма"] for x in строки),
            "максимум": sum(веса.values())}


# ------------------------------------------------------------------- расчёт
def посчитать(s, day=None):
    """Все показатели месяца — по филиалам и в целом."""
    day = day or date.today()
    к = кухня(s, day)
    сч = счета(s, day)
    выручка = sum(v["выручка"] for v in к.values())

    # По филиалам: у каждого своя выручка, свои списания и свой переучёт.
    for имя, v in к.items():
        мои = сч.get(имя, {})
        v["списание"] = sum(мои.get(c, 0) for c in СЧЕТА_СПИСАНИЯ)
        v["переучёт"] = sum(мои.get(c, 0) for c in СЧЕТА_ПЕРЕУЧЁТА)
        v["списание_%"] = v["списание"] / v["выручка"] * 100 if v["выручка"] else 0
        v["переучёт_%"] = v["переучёт"] / v["выручка"] * 100 if v["выручка"] else 0
        v["счета"] = мои
        v["норма_времени"] = НОРМА["время_су"].get(имя)

    общие = сч.get("ВСЕГО", {})
    списание = sum(общие.get(c, 0) for c in СЧЕТА_СПИСАНИЯ)
    переучёт = sum(общие.get(c, 0) for c in СЧЕТА_ПЕРЕУЧЁТА)
    заказов = sum(v["заказов"] for v in к.values())

    негатив = None
    try:
        негатив = негатив_по_качеству(day)
    except Exception:
        pass

    время = [v["время"] for v in к.values() if v["время"]]
    return {
        "месяц": day.strftime("%Y-%m"),
        "точки": к,
        "выручка": выручка,
        "списание": списание,
        "списание_%": списание / выручка * 100 if выручка else 0,
        "переучёт": переучёт,
        "переучёт_%": переучёт / выручка * 100 if выручка else 0,
        "заказов": заказов,
        "негатив": негатив,
        "негатив_%": (негатив / заказов * 100) if негатив and заказов else 0,
        "время_среднее": sum(время) / len(время) if время else 0,
        "тайники": тайники(day),
        "счета": {c: общие.get(c, 0) for c in СЧЕТА_СПИСАНИЯ + СЧЕТА_ПЕРЕУЧЁТА},
    }
