#!/bin/sh
# Обёртка для ssh-ключа читающей сессии.
#
# Ключ прописан в authorized_keys с command="~/app/cappi-core/deploy/айка-ключ.sh",
# поэтому никакая другая команда с ним не выполнится: ssh подставляет сюда
# то, что просили, в SSH_ORIGINAL_COMMAND, а мы это игнорируем и пускаем
# только айка.py с его аргументами. Ни shell, ни scp, ни доступ к файлам.
set -e
cd "$(dirname "$0")/.."
# Аргументы берём из того, что попросили, но команду задаём сами.
set -- $SSH_ORIGINAL_COMMAND
exec python3 айка.py "$@"
